#!/usr/bin/env python3
"""108: catálogo y CHECKs reales en PostgreSQL privado; sin .env/TCP/destino remoto."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
MIGRATION = ROOT/'migrations/108_vivero_embolsado_cierre_catalogo.sql'
NAMES = ['chk_evento_lote_vivero_saldos_eventos_vivos_requeridos', 'chk_evento_lote_vivero_embolsado_consistente']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pg-bin', type=Path, required=True)
    parser.add_argument('--evidence', type=Path)
    args = parser.parse_args()
    if args.evidence and args.evidence.exists(): parser.error('La evidencia debe ser nueva.')
    binaries = {n: str(args.pg_bin/n) for n in ('initdb', 'pg_ctl', 'psql')}
    env = {k:v for k,v in os.environ.items() if not k.startswith('PG')}
    env.update(PGPASSFILE=os.devnull, PGSERVICEFILE=os.devnull, LC_ALL='C')
    directory = Path(tempfile.mkdtemp(prefix='t5-108-', dir='/tmp')).resolve()
    cluster, socket = directory/'pg', directory/'socket'
    socket.mkdir(mode=0o700)
    started = False
    checks = []
    version = None
    migration = MIGRATION.read_text()
    observed = json.loads((ROOT/'docs/evidencia/t5-entorno-migrado-catalogo-2026-11-14.json').read_text())['catalogo']['checks_embolsado']
    before = {
        NAMES[0]: "CHECK (tipo_evento NOT IN ('EMBOLSADO','MERMA','DESPACHO') OR (saldo_vivo_antes IS NOT NULL AND saldo_vivo_despues IS NOT NULL))",
        NAMES[1]: "CHECK (tipo_evento<>'EMBOLSADO' OR (saldo_vivo_antes=0 AND cantidad_afectada IS NOT NULL AND cantidad_afectada=saldo_vivo_despues::numeric))",
    }
    source095 = (ROOT/'migrations/095_vivero_operacion_por_ambito.sql').read_text()
    function = re.search(r'CREATE OR REPLACE FUNCTION public\.fn_vivero_registrar_embolsado\([\s\S]+?\$\$;', source095).group(0)

    def run(cmd):
        r = subprocess.run(cmd, env=env, text=True, capture_output=True, timeout=60)
        if r.returncode: raise RuntimeError(r.stderr[-2500:])
        return r.stdout.strip()

    def command():
        return [binaries['psql'], '-X', '-w', '-qAt', '-v', 'ON_ERROR_STOP=1', '-h', str(socket), '-p', '55445', '-U', 'postgres', '-d', 'postgres']

    def sql(statement, error=None):
        r = subprocess.run(command()+['-c', statement], env=env, text=True, capture_output=True, timeout=40)
        if error:
            if not r.returncode or error not in r.stderr: raise AssertionError(f'Esperado {error}: {r.stderr[-2000:]}')
        elif r.returncode: raise RuntimeError(r.stderr[-2500:])
        return r.stdout.strip()

    def check(condition, label):
        if not condition: raise AssertionError(label)
        checks.append(label)

    def snapshot():
        return sql("SELECT jsonb_build_object('filas',(SELECT jsonb_agg(to_jsonb(e) ORDER BY id) FROM public.evento_lote_vivero e),'checks',(SELECT jsonb_agg(jsonb_build_array(conname,pg_get_constraintdef(oid),convalidated) ORDER BY conname) FROM pg_constraint WHERE conrelid='public.evento_lote_vivero'::regclass),'rpc',(SELECT pg_get_functiondef('public.fn_vivero_registrar_embolsado(bigint,date,bigint,integer,text,bigint[])'::regprocedure)))")

    def initialize(variant):
        sql('DROP SCHEMA public CASCADE; CREATE SCHEMA public;')
        run(command()+['-f', str(ROOT/'migrations/006_vivero_enums.sql')])
        sql("ALTER TYPE public.tipo_evento_vivero ADD VALUE 'INCORPORACION'")
        sql("CREATE TABLE public.evento_lote_vivero(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,tipo_evento public.tipo_evento_vivero NOT NULL,saldo_vivo_antes integer,saldo_vivo_despues integer,cantidad_afectada numeric,unidad_medida_evento public.unidad_medida);")
        sql(function)
        constraints = {c['nombre']: c['definicion'] for c in observed} if variant=='observado' else before
        for name, expression in constraints.items(): sql(f'ALTER TABLE public.evento_lote_vivero ADD CONSTRAINT {name} {expression}')
        if variant=='107': run(command()+['-f', str(ROOT/'migrations/107_vivero_embolsado_saldo_naciente.sql')])
        saldo = '0' if variant=='010' else 'NULL'
        sql(f"INSERT INTO public.evento_lote_vivero(tipo_evento,saldo_vivo_antes,saldo_vivo_despues,cantidad_afectada,unidad_medida_evento) VALUES('EMBOLSADO',{saldo},10,10,'UNIDAD'),('MERMA',10,8,2,'UNIDAD'),('DESPACHO',8,6,2,'UNIDAD'),('INICIO',NULL,NULL,1,'G'),('INCORPORACION',0,10,10,'UNIDAD')")

    try:
        run([binaries['initdb'], '-D', str(cluster), '-U', 'postgres', '--auth-local=trust', '--auth-host=reject', '--locale=en_US.UTF-8', '--encoding=UTF8'])
        run([binaries['pg_ctl'], '-D', str(cluster), '-l', str(directory/'pg.log'), '-w', '-t', '20', 'start', '-o', f"-c listen_addresses='' -c unix_socket_directories='{socket}' -c port=55445 -c unix_socket_permissions=0700"])
        started = True
        version = sql('SHOW server_version')
        for variant in ('010', '107', 'observado'):
            initialize(variant)
            rows_before = json.loads(snapshot())['filas']
            function_before = json.loads(snapshot())['rpc']
            run(command()+['-f', str(MIGRATION)])
            first = snapshot()
            run(command()+['-f', str(MIGRATION)])
            check(first==snapshot(), f'{variant}: instalación/repetición108 conserva filas, RPC y CHECKs validados')
            check(rows_before==json.loads(first)['filas'] and function_before==json.loads(first)['rpc'], f'{variant}: no reescribe IDs, saldos ni RPC095')
            # Nuevo saldo anteriorNULL y cero legado siguen siendo válidos.
            sql("INSERT INTO public.evento_lote_vivero(tipo_evento,saldo_vivo_antes,saldo_vivo_despues,cantidad_afectada,unidad_medida_evento) VALUES('EMBOLSADO',NULL,2,2,'UNIDAD'),('EMBOLSADO',0,2,2,'UNIDAD')")
            before_invalid = snapshot()
            for quantity, prior, after, unit in [('0','NULL','0',"'UNIDAD'"),('1.5','NULL','1',"'UNIDAD'"),('-1','NULL','1',"'UNIDAD'"),('1','1','1',"'UNIDAD'"),('1','NULL','2',"'UNIDAD'"),('1','NULL','NULL',"'UNIDAD'"),('NULL','NULL','1',"'UNIDAD'"),('1','NULL','1',"'G'"),('1','NULL','1','NULL')]:
                sql(f"INSERT INTO public.evento_lote_vivero(tipo_evento,saldo_vivo_antes,saldo_vivo_despues,cantidad_afectada,unidad_medida_evento) VALUES('EMBOLSADO',{prior},{after},{quantity},{unit})", error='check constraint')
            for event in ('MERMA','DESPACHO'):
                for prior, after in [('NULL','1'),('1','NULL'),('-1','0'),('0','-1')]:
                    sql(f"INSERT INTO public.evento_lote_vivero(tipo_evento,saldo_vivo_antes,saldo_vivo_despues,cantidad_afectada,unidad_medida_evento) VALUES('{event}',{prior},{after},1,'UNIDAD')", error='check constraint')
            check(before_invalid==snapshot(), f'{variant}: rechaza nueve EMBOLSADO incoherentes y ocho MERMA/DESPACHO sin saldos válidos')
            for name in NAMES:
                for mode in ('ausente', 'deriva', 'no_validada'):
                    replacement = '' if mode=='ausente' else f'ALTER TABLE public.evento_lote_vivero ADD CONSTRAINT {name} CHECK (true)' if mode=='deriva' else f'ALTER TABLE public.evento_lote_vivero ADD CONSTRAINT {name} '+json.loads(snapshot())['checks'][1 if name==NAMES[0] else 0][1]+' NOT VALID'
                    statement = 'BEGIN; ALTER TABLE public.evento_lote_vivero DROP CONSTRAINT '+name+'; '+replacement+'; '+migration.replace('BEGIN;', '', 1)
                    sql(statement, error='T5_EMBOLSADO_108_CHECK_INCOMPATIBLE')
                    check(before_invalid==snapshot(), f'{variant}: aborta y revierte CHECK {name}/{mode}')
            sql('BEGIN; ALTER FUNCTION public.fn_vivero_registrar_embolsado(bigint,date,bigint,integer,text,bigint[]) SECURITY INVOKER; '+migration.replace('BEGIN;', '', 1), error='T5_EMBOLSADO_108_RPC_INCOMPATIBLE')
            check(before_invalid==snapshot(), f'{variant}: aborta ante seguridad RPC distinta sin cambios')
            sql('BEGIN; '+function.replace('AS $$', 'AS $$\n-- deriva de ensayo', 1)+'; '+migration.replace('BEGIN;', '', 1), error='T5_EMBOLSADO_108_RPC_INCOMPATIBLE')
            check(before_invalid==snapshot(), f'{variant}: aborta ante cuerpo RPC distinto sin cambios')
        for quantity, after, unit in [('0','0',"'UNIDAD'"),('2','2','NULL'),('2','2',"'G'")]:
            initialize('observado')
            sql(f"INSERT INTO public.evento_lote_vivero(tipo_evento,saldo_vivo_antes,saldo_vivo_despues,cantidad_afectada,unidad_medida_evento) VALUES('EMBOLSADO',NULL,{after},{quantity},{unit})")
            prior = snapshot()
            sql(migration, error='T5_EMBOLSADO_108_DATOS_INCOMPATIBLES')
            check(prior==snapshot(), 'Datos ambiguos admitidos por CHECK legado NULL impiden108 sin reescritura: '+quantity+'/'+after+'/'+unit)
        initialize('010')
        sql("INSERT INTO public.evento_lote_vivero(tipo_evento,saldo_vivo_antes,saldo_vivo_despues,cantidad_afectada,unidad_medida_evento) VALUES('MERMA',1,-1,2,'UNIDAD')")
        prior = snapshot()
        sql(migration, error='T5_EMBOLSADO_108_DATOS_INCOMPATIBLES')
        check(prior==snapshot(), 'MERMA negativa heredada010 impide108; preserva historia para revisión')
        if args.evidence:
            args.evidence.write_text(json.dumps({'fecha_utc':datetime.now(timezone.utc).isoformat(),'postgresql':version,'resultado':'APROBADO','grupos':len(checks),'comprobaciones':checks,'sha256_migracion':hashlib.sha256(MIGRATION.read_bytes()).hexdigest(),'limites':['Clúster PostgreSQL privado sin TCP/.env; destruido al finalizar.','Fixture focal de catálogo/CHECKs con RPC095 exacta no invocada; no replay productivo ni Supabase/Storage remoto.','Conservación de filas, función095 y catálogo ante rollback; IDs de secuencias pueden avanzar por INSERT fallido como en PostgreSQL.']}, ensure_ascii=False, indent=2)+'\n')
        print(f'108: {len(checks)} grupos aprobados en PostgreSQL {version}.')
    finally:
        if started: subprocess.run([binaries['pg_ctl'], '-D', str(cluster), '-m', 'immediate', '-w', 'stop'], env=env, capture_output=True, text=True)
        shutil.rmtree(directory)


if __name__=='__main__': main()
