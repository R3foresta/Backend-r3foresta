#!/usr/bin/env python3
"""Verifica el cotejador INT07 en un PostgreSQL privado, desechable y sin TCP.

No carga .env, no usa conexiones existentes y no requiere PostGIS. Solo escribe
evidencia si se pasa --evidence; las pruebas no acreditan un destino externo.
"""

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[2]
SQL = ROOT / 'scripts/qa/pa-int07-catalogo.sql'
PORT = '55437'  # Solo socket UNIX exclusivo del clúster; listen_addresses vacío.


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pg-bin', type=Path,
                        help='Directorio con initdb, pg_ctl y psql; por defecto PATH.')
    parser.add_argument('--evidence', type=Path,
                        help='Archivo JSON de evidencia; no se escribe por defecto.')
    args = parser.parse_args()

    binaries = {}
    for name in ('initdb', 'pg_ctl', 'psql'):
        candidate = (args.pg_bin.expanduser().resolve() / name) if args.pg_bin else shutil.which(name)
        if not candidate or not Path(candidate).is_file() or not os.access(candidate, os.X_OK):
            parser.error(f'No se encontró {name}; indique --pg-bin o configure PATH.')
        binaries[name] = str(Path(candidate).resolve())
    if not SQL.is_file():
        parser.error('No se encontró scripts/qa/pa-int07-catalogo.sql.')
    evidence = args.evidence.expanduser().resolve() if args.evidence else None
    if evidence and (evidence.exists() or not evidence.parent.is_dir()):
        parser.error('--evidence requiere un archivo nuevo dentro de un directorio existente.')

    env = {k: v for k, v in os.environ.items() if not k.startswith('PG')}
    env.update(LC_ALL='C', PGAPPNAME='pa_int07_catalogo_aislado',
               PGPASSFILE=os.devnull, PGSERVICEFILE=os.devnull)
    # /tmp evita exceder el límite de longitud del socket UNIX en macOS. mkdtemp
    # crea un directorio nuevo 0700; nunca se reutiliza ni borra una ruta recibida.
    directory = Path(tempfile.mkdtemp(prefix='pa-int07-', dir='/tmp')).resolve()
    cluster = directory / 'postgres'
    socket = directory / 'socket'
    checks = []
    start_attempted = False

    def run(command, rejection=False):
        result = subprocess.run(command, env=env, text=True, capture_output=True,
                                timeout=40, check=False)
        if not rejection and result.returncode != 0:
            raise RuntimeError(result.stderr[-3500:] or 'Falló un comando PostgreSQL aislado.')
        if rejection and (result.returncode == 0 or 'read-only transaction' not in result.stderr):
            raise RuntimeError('La escritura debe rechazarse específicamente por READ ONLY.')
        return result

    def psql(*arguments, rejection=False):
        return run([binaries['psql'], '-X', '-w', '-qAt', '-v', 'ON_ERROR_STOP=1',
                    '-h', str(socket), '-p', PORT, '-U', 'postgres', '-d', 'postgres',
                    *arguments], rejection=rejection).stdout.strip()

    def check(condition, description):
        if not condition:
            raise AssertionError(description)
        checks.append(description)

    def exists_grant(rows, **expected):
        return any(all(row.get(key) == value for key, value in expected.items()) for row in rows)

    try:
        socket.mkdir(mode=0o700)
        run([binaries['initdb'], '-D', str(cluster), '-U', 'postgres',
             '--auth-local=trust', '--auth-host=reject', '--locale=C', '--encoding=UTF8'])
        start_attempted = True
        run([binaries['pg_ctl'], '-D', str(cluster), '-l', str(directory / 'postgres.log'),
             '-w', '-t', '20', 'start', '-o',
             "-c listen_addresses='' -c unix_socket_directories='" + str(socket)
             + "' -c unix_socket_permissions=0700 -c port=" + PORT + ' -c shared_buffers=16MB'])

        empty = json.loads(psql('-f', str(SQL)))
        check(empty['entorno']['solo_lectura'] == 'on', 'Transacción READ ONLY real')
        check(psql('-c', 'SHOW listen_addresses') == '', 'Clúster privado sin escucha TCP')
        check(empty['entorno']['aislamiento'] == 'repeatable read', 'Snapshot REPEATABLE READ')
        check(not any(row['existe'] for row in empty['objetos_esperados']),
              'Objetos ausentes informados sin abortar')
        check([row['rol'] for row in empty['roles'] if row['existe']] == ['PUBLIC'],
              'Roles ausentes tolerados y PUBLIC como pseudorol')

        fixture = '''
CREATE ROLE anon;
CREATE ROLE authenticated;
CREATE ROLE service_role;
CREATE ROLE pa_int07_lectores;
GRANT pa_int07_lectores TO anon;
CREATE TABLE public.registro_plantacion(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cantidad_muerta_acumulada int NOT NULL DEFAULT 0 CHECK(cantidad_muerta_acumulada>=0),
 observaciones text DEFAULT 'SENTINELA_PRIVADA_INT07');
CREATE TABLE public.evento_plantacion(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 registro_plantacion_id bigint REFERENCES public.registro_plantacion(id),
 cantidad_muerta_delta int);
INSERT INTO public.registro_plantacion(cantidad_muerta_acumulada) VALUES (0);
CREATE SCHEMA pa_int07_mantenimiento;
CREATE VIEW public.pa_int07_v1 AS SELECT id FROM public.registro_plantacion;
CREATE VIEW pa_int07_mantenimiento.pa_int07_v2 AS SELECT id FROM public.pa_int07_v1;
CREATE FUNCTION pa_int07_mantenimiento.mortandad_escritor() RETURNS trigger LANGUAGE plpgsql AS $$
 BEGIN UPDATE public.registro_plantacion
 SET cantidad_muerta_acumulada=cantidad_muerta_acumulada+NEW.cantidad_muerta_delta
 WHERE id=NEW.registro_plantacion_id; RETURN NEW; END $$;
CREATE TRIGGER pa_int07_mortandad AFTER INSERT ON public.evento_plantacion
 FOR EACH ROW EXECUTE FUNCTION pa_int07_mantenimiento.mortandad_escritor();
CREATE FUNCTION pa_int07_mantenimiento.mortandad_escritor(text) RETURNS text
 LANGUAGE sql AS $$ SELECT $1 $$;
REVOKE ALL ON FUNCTION pa_int07_mantenimiento.mortandad_escritor(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION pa_int07_mantenimiento.mortandad_escritor(text) TO service_role;
GRANT SELECT ON public.registro_plantacion TO pa_int07_lectores;
GRANT INSERT ON public.evento_plantacion TO PUBLIC;
GRANT UPDATE(observaciones) ON public.registro_plantacion TO authenticated;
GRANT USAGE ON SEQUENCE public.registro_plantacion_id_seq TO pa_int07_lectores;
ALTER TABLE public.registro_plantacion ENABLE ROW LEVEL SECURITY;
CREATE POLICY pa_int07_privada ON public.registro_plantacion TO service_role USING (id>0);
-- ACL vacía explícita no equivale a NULL/default, especialmente en funciones.
CREATE FUNCTION public.pa_int07_acl_vacia() RETURNS int LANGUAGE sql AS $$ SELECT 1 $$;
REVOKE ALL ON FUNCTION public.pa_int07_acl_vacia() FROM PUBLIC, postgres;
CREATE TABLE public.subcampania(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
REVOKE ALL ON TABLE public.subcampania FROM PUBLIC, postgres;
REVOKE ALL ON SEQUENCE public.subcampania_id_seq FROM PUBLIC, postgres;
CREATE SCHEMA pa_int07_acl_vacio;
CREATE VIEW pa_int07_acl_vacio.pa_int07_vacia AS SELECT id FROM public.registro_plantacion;
REVOKE ALL ON SCHEMA pa_int07_acl_vacio FROM PUBLIC, postgres;
'''
        psql('-c', fixture)
        empty_acl = json.loads(psql('-c', '''SELECT jsonb_build_object(
 'funcion',(SELECT cardinality(proacl)=0 FROM pg_proc WHERE oid='public.pa_int07_acl_vacia()'::regprocedure),
 'tabla',(SELECT cardinality(relacl)=0 FROM pg_class WHERE oid='public.subcampania'::regclass),
 'secuencia',(SELECT cardinality(relacl)=0 FROM pg_class WHERE oid='public.subcampania_id_seq'::regclass),
 'esquema',(SELECT cardinality(nspacl)=0 FROM pg_namespace WHERE nspname='pa_int07_acl_vacio'))'''))
        check(all(value is True for value in empty_acl.values()),
              'Fixture crea ACL explícita vacía de función, tabla, secuencia y esquema')

        marker = '''SELECT jsonb_build_object(
 'registros',(SELECT jsonb_agg(to_jsonb(r)) FROM public.registro_plantacion r),
 'eventos',(SELECT count(*) FROM public.evento_plantacion),
 'secuencia',(SELECT last_value FROM public.registro_plantacion_id_seq))'''
        before = psql('-c', marker)
        raw = psql('-f', str(SQL))
        observed = json.loads(raw)
        check(observed == json.loads(psql('-f', str(SQL))),
              'Cotejo repetible sin efectos de negocio o catálogo')
        check(before == psql('-c', marker), 'Filas, contadores y valor de secuencia intactos')
        check('SENTINELA_PRIVADA_INT07' not in raw and 'UPDATE public' not in raw,
              'Sin filas, defaults, expresiones o cuerpos SQL completos')
        check(exists_grant(observed['relaciones'], esquema='pa_int07_mantenimiento', nombre='pa_int07_v2'),
              'Descubre vistas dependientes transitivas en otros esquemas')
        check(any(row['tipo'] == 'f' for row in observed['restricciones']),
              'Inventaría FKs y restricciones reales')
        check(exists_grant(observed['triggers'], nombre='pa_int07_mortandad'),
              'Inventaría trigger real adjunto')
        functions = [f for f in observed['funciones_candidatas'] if f['nombre'] == 'mortandad_escritor']
        check(len(functions) == 2 and all(len(f['definicion_md5']) == 32 for f in functions),
              'Descubre escritor fuera de public y todos sus overloads mediante huellas')
        check(any(f['trigger_adjunto'] and f['referencia_grupo_mortandad'] for f in functions),
              'Marca candidato de mortandad/trigger sin afirmar disciplina de locks')
        privileges = observed['privilegios']
        check(exists_grant(privileges['tablas_vistas'], rol='anon', relname='registro_plantacion',
                           privilegio='SELECT', concedido=True), 'Detecta SELECT heredado por anon')
        check(exists_grant(privileges['tablas_vistas'], rol='PUBLIC', relname='evento_plantacion',
                           privilegio='INSERT', concedido=True), 'Detecta privilegio de PUBLIC pseudorol')
        check(exists_grant(privileges['columnas'], rol='authenticated', columna='observaciones',
                           privilegio='UPDATE', concedido=True), 'Detecta UPDATE específico de columna')
        check(not exists_grant(privileges['tablas_vistas'], rol='authenticated', relname='registro_plantacion',
                               privilegio='UPDATE', concedido=True),
              'No confunde grant de columna con UPDATE de tabla')
        check(exists_grant(privileges['secuencias'], rol='anon', privilegio='USAGE', concedido=True),
              'Detecta USAGE de secuencia heredado')
        check(exists_grant(privileges['funciones'], rol='service_role', nombre='mortandad_escritor',
                           argumentos='text', execute=True), 'Detecta EXECUTE privado de overload')
        check(exists_grant(privileges['funciones'], rol='PUBLIC', nombre='mortandad_escritor',
                           argumentos='', execute=True), 'Conserva EXECUTE PUBLIC por default en la otra sobrecarga')
        check(exists_grant(privileges['funciones'], rol='PUBLIC', nombre='pa_int07_acl_vacia', execute=False),
              'ACL función {} no recupera EXECUTE PUBLIC del default')
        empty_table = [row for row in privileges['tablas_vistas']
                       if row['rol'] == 'PUBLIC' and row['relname'] == 'subcampania']
        empty_sequence = [row for row in privileges['secuencias']
                          if row['rol'] == 'PUBLIC' and row['secuencia'] == 'subcampania_id_seq']
        empty_schema = [row for row in privileges['esquemas']
                        if row['rol'] == 'PUBLIC' and row['esquema'] == 'pa_int07_acl_vacio']
        check(bool(empty_table) and all(row['concedido'] is False for row in empty_table),
              'ACL tabla {} se procesa sin conceder privilegios PUBLIC')
        check(bool(empty_sequence) and all(row['concedido'] is False for row in empty_sequence),
              'ACL secuencia {} se procesa sin conceder privilegios PUBLIC')
        check(bool(empty_schema) and all(row['concedido'] is False for row in empty_schema),
              'ACL esquema {} se procesa sin conceder privilegios PUBLIC')
        check(exists_grant(observed['politicas_rls'], nombre='pa_int07_privada'),
              'Inventaría RLS y huellas de políticas sin expresiones')
        injected = SQL.read_text().replace('ROLLBACK;',
            'INSERT INTO public.registro_plantacion(cantidad_muerta_acumulada) VALUES(1);\nROLLBACK;')
        psql('-c', injected, rejection=True)
        check(before == psql('-c', marker), 'READ ONLY rechaza escritura inyectada y conserva el estado')
        result = {
            'postgresql': psql('-c', 'SHOW server_version'),
            'postgis': False,
            'entorno': 'CLUSTER_SINTETICO_DESECHABLE_SIN_TCP_SIN_ENV',
            'comprobaciones': checks,
            'limites': ['Verifica utilidad de catálogo, no SQL ni RPC de INT07.',
                        'No acredita escritores, locks, datos o privilegios del destino Supabase.',
                        'No requiere ni verifica PostGIS.'],
        }
        if evidence:
            # Modo exclusivo: jamás sobrescribe evidencia anterior.
            with evidence.open('x', encoding='utf-8') as handle:
                handle.write(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
        print(json.dumps({'estado': 'APROBADO', 'comprobaciones': len(checks),
                          'postgresql': result['postgresql']}, ensure_ascii=False))
    finally:
        # Aunque start falle después de arrancar, solo se detiene el clúster cuyo
        # directorio acabamos de crear. Si no puede detenerse, se preserva la ruta.
        can_remove = True
        if start_attempted and (cluster / 'postmaster.pid').exists():
            stopped = subprocess.run([binaries['pg_ctl'], '-D', str(cluster), '-m',
                                      'immediate', '-w', '-t', '20', 'stop'],
                                     env=env, capture_output=True, timeout=25, check=False)
            can_remove = stopped.returncode == 0
        if can_remove:
            if directory.is_symlink() or not directory.is_dir() or cluster.parent != directory:
                raise RuntimeError('Se rechazó limpiar una ruta que no corresponde al clúster temporal.')
            shutil.rmtree(directory)
        else:
            raise RuntimeError(f'No se pudo detener el clúster temporal; se conservó {directory}.')


if __name__ == '__main__':
    main()
