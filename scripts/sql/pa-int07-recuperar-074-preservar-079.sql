-- Ledger durable. BORRADO_VERIFICADO se vuelve a barrer: un upload antiguo puede reaparecer.
CREATE OR REPLACE FUNCTION public.pa_cargas_mantenimiento(p_accion TEXT,p_payload JSONB DEFAULT '{}') RETURNS JSONB LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public AS $$
DECLARE c public.participacion_comando%ROWTYPE; f public.participacion_carga%ROWTYPE; g public.participacion_carga_generacion%ROWTYPE; r JSONB;
BEGIN
  IF p_accion='EXPIRAR' THEN
    FOR c IN SELECT * FROM public.participacion_comando x WHERE (estado='PREPARADO' AND creado_en<=clock_timestamp()-interval '30 days') OR EXISTS(SELECT 1 FROM public.participacion_carga xc WHERE xc.comando_interno_id=x.id AND xc.estado IN ('RESERVADA','DISPONIBLE') AND xc.expira_en<=clock_timestamp()) ORDER BY actor_id,subcampania_preparacion_id,id LIMIT 1 LOOP
      PERFORM 1 FROM public.usuario WHERE id=c.actor_id FOR SHARE;
      PERFORM 1 FROM public.subcampania WHERE id=c.subcampania_preparacion_id FOR UPDATE;
      PERFORM pg_advisory_xact_lock(hashtextextended('pa:comando:'||c.actor_id||':REGISTRAR_PLANTACION_INICIAL:'||c.comando_id,0));
      SELECT * INTO c FROM public.participacion_comando WHERE id=c.id FOR UPDATE;
      PERFORM 1 FROM public.participacion_carga WHERE comando_interno_id=c.id ORDER BY id FOR UPDATE;
      PERFORM 1 FROM public.participacion_carga_generacion WHERE carga_interna_id IN (SELECT id FROM public.participacion_carga WHERE comando_interno_id=c.id) ORDER BY carga_interna_id,generacion FOR UPDATE;
      IF c.estado='PREPARADO' THEN UPDATE public.participacion_comando SET estado='RECHAZADO',error=public.pa_c_error('PREPARACION_CANCELADA','La preparación expiró.','NO_APLICA'),http_terminal=409,finalizado_en=clock_timestamp() WHERE id=c.id; END IF;
      UPDATE public.participacion_carga_generacion SET estado='OBSOLETA',limpieza_estado='PENDIENTE',proximo_intento_en=clock_timestamp() WHERE carga_interna_id IN (SELECT id FROM public.participacion_carga WHERE comando_interno_id=c.id AND estado<>'VINCULADA');
      UPDATE public.participacion_carga SET estado='DESCARTE_PENDIENTE',lease_token=NULL,lease_hasta=NULL,actualizado_en=clock_timestamp() WHERE comando_interno_id=c.id AND estado NOT IN ('VINCULADA','DESCARTADA');
      RETURN 'true';
    END LOOP;
    RETURN 'false';
  END IF;
  IF p_accion='LISTAR' THEN
    SELECT COALESCE(jsonb_agg(jsonb_build_object('carga_interna_id',x.carga_interna_id::text,'generacion',x.generacion,'bucket',x.bucket,'ruta_original',x.ruta_original,'ruta_derivada',x.ruta_derivada)),'[]') INTO r FROM (SELECT xg.* FROM public.participacion_carga_generacion xg
      JOIN public.participacion_carga xc ON xc.id=xg.carga_interna_id WHERE xg.estado='OBSOLETA' AND NOT (xc.estado='VINCULADA' AND xc.generacion=xg.generacion)
      AND NOT EXISTS(SELECT 1 FROM public.evidencias_trazabilidad ev WHERE ev.bucket=xg.bucket AND ev.ruta_archivo IN (xg.ruta_original,xg.ruta_derivada) AND ev.entidad_id IS NOT NULL AND ev.entidad_id<>0)
      AND COALESCE(xg.proximo_intento_en,xg.creado_en)<=clock_timestamp() ORDER BY xg.carga_interna_id,xg.generacion LIMIT 100) x;
    RETURN r;
  END IF;
  IF p_accion='RESULTADO' THEN
    SELECT * INTO f FROM public.participacion_carga WHERE id=(p_payload->>'carga_interna_id')::bigint FOR UPDATE;
    SELECT * INTO g FROM public.participacion_carga_generacion WHERE carga_interna_id=f.id AND generacion=(p_payload->>'generacion')::integer FOR UPDATE;
    IF g.estado<>'OBSOLETA' OR (f.estado='VINCULADA' AND f.generacion=g.generacion)
      OR EXISTS(SELECT 1 FROM public.evidencias_trazabilidad ev WHERE ev.bucket=g.bucket AND ev.ruta_archivo IN (g.ruta_original,g.ruta_derivada) AND ev.entidad_id IS NOT NULL AND ev.entidad_id<>0) THEN RETURN '[]'; END IF;
    UPDATE public.participacion_carga_generacion SET limpieza_estado=CASE WHEN p_payload->>'borrado'='true' THEN 'BORRADO_VERIFICADO' ELSE 'PENDIENTE' END,
      borrado_verificado_en=CASE WHEN p_payload->>'borrado'='true' THEN clock_timestamp() ELSE borrado_verificado_en END,
      proximo_intento_en=clock_timestamp()+interval '5 minutes' WHERE carga_interna_id=f.id AND generacion=g.generacion;
    IF f.estado='DESCARTE_PENDIENTE' AND NOT EXISTS(SELECT 1 FROM public.participacion_carga_generacion WHERE carga_interna_id=f.id AND limpieza_estado<>'BORRADO_VERIFICADO') THEN
      UPDATE public.participacion_carga SET estado='DESCARTADA',actualizado_en=clock_timestamp() WHERE id=f.id;
    END IF;
    RETURN '[]';
  END IF;
  RAISE EXCEPTION 'PA_CARGAS_ACCION_INVALIDA';
END $$;

