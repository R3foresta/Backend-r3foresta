-- Todo IO de Storage ocurre entre RESERVAR y FINALIZAR, fuera de esta transacción.
CREATE OR REPLACE FUNCTION public.pa_cargas_operar(p_actor_id BIGINT,p_auth_id TEXT,p_accion TEXT,p_comando_id UUID DEFAULT NULL,p_payload JSONB DEFAULT '{}')
RETURNS JSONB LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public AS $$
DECLARE a public.usuario%ROWTYPE; c public.participacion_comando%ROWTYPE; f public.participacion_carga%ROWTYPE;
  s public.subcampania%ROWTYPE; g public.participacion_carga_generacion%ROWTYPE; v_scope BIGINT; v_tipo BIGINT;
  v_lease UUID; v_gen INTEGER; v_ruta TEXT; v_evidencia BIGINT; v_nuevo BOOLEAN:=false; v_carga UUID; v_expirada BOOLEAN:=false;
BEGIN
  PERFORM set_config('lock_timeout','5s',true);
  PERFORM set_config('statement_timeout','30s',true);
  SELECT * INTO a FROM public.usuario WHERE id=p_actor_id AND auth_id=p_auth_id FOR SHARE;
  IF NOT FOUND THEN RETURN public.pa_c_fuera(401,'SESION_INVALIDA','La sesión no es válida.',p_comando_id,'RECUPERAR_SESION'); END IF;
  IF NOT a.activo THEN RETURN public.pa_c_fuera(403,'CUENTA_INACTIVA','La cuenta no está activa.',p_comando_id); END IF;
  IF p_accion='PREVIEW' THEN
    SELECT * INTO f FROM public.participacion_carga WHERE actor_id=p_actor_id AND carga_id=(p_payload->>'carga_id')::uuid;
    IF NOT FOUND OR f.estado NOT IN ('DISPONIBLE','VINCULADA') OR (f.estado='DISPONIBLE' AND f.expira_en<=clock_timestamp()) THEN RETURN public.pa_c_fuera(404,'CARGA_NO_ENCONTRADA','La carga no está disponible.',p_comando_id); END IF;
    RETURN public.pa_cargas_respuesta(200,jsonb_build_object('bucket',f.bucket,'ruta_derivada',f.ruta_derivada));
  END IF;
  SELECT * INTO c FROM public.participacion_comando WHERE actor_id=p_actor_id AND operacion='REGISTRAR_PLANTACION_INICIAL' AND comando_id=p_comando_id;
  IF p_accion='PREPARAR' THEN
    v_scope:=(p_payload->>'subcampania_id')::bigint;
    IF c.id IS NOT NULL THEN
      IF c.subcampania_preparacion_id<>v_scope THEN RETURN public.pa_c_fuera(409,'COMANDO_REUTILIZADO','La clave corresponde a otro ámbito.',p_comando_id,'MISMA_CLAVE'); END IF;
      IF c.estado<>'PREPARADO' THEN RETURN public.pa_c_recibo(c,true); END IF;
    END IF;
  ELSE
    IF c.id IS NULL THEN RETURN public.pa_c_fuera(404,'COMANDO_NO_ENCONTRADO','No se encontró la preparación propia.',p_comando_id,'MISMA_CLAVE'); END IF;
    v_scope:=c.subcampania_preparacion_id;
  END IF;
  IF p_accion='LISTAR' THEN
    RETURN public.pa_cargas_respuesta(200,COALESCE((SELECT jsonb_agg(public.pa_carga_dto(x) ORDER BY x.id) FROM public.participacion_carga x WHERE comando_interno_id=c.id),'[]'));
  END IF;
  IF p_accion='RESERVAR' THEN
    v_carga:=(p_payload->>'carga_id')::uuid;
    SELECT * INTO f FROM public.participacion_carga WHERE actor_id=p_actor_id AND carga_id=v_carga;
    IF f.id IS NOT NULL THEN
      IF f.comando_interno_id<>c.id OR f.hash_original_sha256<>decode(p_payload->>'hash_original','hex') THEN RETURN public.pa_c_fuera(409,'CARGA_REUTILIZADA','La carga corresponde a otra identidad o bytes.',p_comando_id,'MISMA_CLAVE'); END IF;
      IF f.estado='VINCULADA' OR (f.estado='DISPONIBLE' AND f.expira_en>clock_timestamp()) THEN RETURN public.pa_cargas_respuesta(200,public.pa_carga_dto(f)); END IF;
    END IF;
  END IF;
  -- Cuenta → ámbito → exclusión/registro comando → cargas → generaciones → evidencias.
  SELECT * INTO s FROM public.subcampania WHERE id=v_scope FOR UPDATE;
  PERFORM pg_advisory_xact_lock(hashtextextended('pa:comando:'||p_actor_id||':REGISTRAR_PLANTACION_INICIAL:'||p_comando_id,0));
  SELECT * INTO c FROM public.participacion_comando WHERE actor_id=p_actor_id AND operacion='REGISTRAR_PLANTACION_INICIAL' AND comando_id=p_comando_id FOR UPDATE;
  IF p_accion='PREPARAR' AND c.id IS NOT NULL AND c.subcampania_preparacion_id<>v_scope THEN RETURN public.pa_c_fuera(409,'COMANDO_REUTILIZADO','La clave corresponde a otro ámbito.',p_comando_id,'MISMA_CLAVE'); END IF;
  IF p_accion='PREPARAR' AND c.id IS NOT NULL AND c.estado<>'PREPARADO' THEN RETURN public.pa_c_recibo(c,true); END IF;
  v_expirada:=c.estado='PREPARADO' AND c.creado_en<=clock_timestamp()-interval '30 days';
  IF p_accion='DESCARTAR' OR v_expirada THEN
    IF c.estado='PREPARADO' THEN
      UPDATE public.participacion_comando SET estado='RECHAZADO',error=public.pa_c_error('PREPARACION_CANCELADA',CASE WHEN v_expirada THEN 'La preparación expiró.' ELSE 'La preparación se canceló.' END,'NO_APLICA'),http_terminal=409,finalizado_en=clock_timestamp() WHERE id=c.id RETURNING * INTO c;
    END IF;
    PERFORM 1 FROM public.participacion_carga WHERE comando_interno_id=c.id ORDER BY id FOR UPDATE;
