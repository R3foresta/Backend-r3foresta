-- Conservar identidad y obligaciones de compensación incluso después de borrar objetos.
CREATE OR REPLACE FUNCTION public.pa_carga_proteger() RETURNS TRIGGER LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public AS $$
BEGIN
  IF TG_OP IN ('DELETE','TRUNCATE') THEN RAISE EXCEPTION 'PA_CARGA_CONSERVACION_OBLIGATORIA'; END IF;
  IF TG_TABLE_NAME='participacion_carga' AND (NEW.actor_id,NEW.carga_id,NEW.comando_origen_id,NEW.subcampania_id,NEW.tipo_entidad_id,NEW.hash_original_sha256,NEW.creado_en)
    IS DISTINCT FROM (OLD.actor_id,OLD.carga_id,OLD.comando_origen_id,OLD.subcampania_id,OLD.tipo_entidad_id,OLD.hash_original_sha256,OLD.creado_en) THEN
    RAISE EXCEPTION 'PA_CARGA_IDENTIDAD_INMUTABLE';
  END IF;
  IF TG_TABLE_NAME='participacion_carga' AND OLD.estado='VINCULADA' AND NEW IS DISTINCT FROM OLD THEN RAISE EXCEPTION 'PA_CARGA_VINCULADA_INMUTABLE'; END IF;
  IF TG_TABLE_NAME='participacion_carga' AND OLD.estado IN ('DESCARTE_PENDIENTE','DESCARTADA') AND NEW.estado NOT IN ('DESCARTE_PENDIENTE','DESCARTADA') THEN RAISE EXCEPTION 'PA_CARGA_NO_REABRIBLE'; END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE FUNCTION public.pa_carga_generacion_proteger() RETURNS TRIGGER LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public AS $$
BEGIN
  IF (NEW.carga_interna_id,NEW.generacion,NEW.bucket,NEW.ruta_original,NEW.ruta_derivada,NEW.lease_token,NEW.lease_hasta,NEW.creado_en)
    IS DISTINCT FROM (OLD.carga_interna_id,OLD.generacion,OLD.bucket,OLD.ruta_original,OLD.ruta_derivada,OLD.lease_token,OLD.lease_hasta,OLD.creado_en) THEN RAISE EXCEPTION 'PA_GENERACION_IDENTIDAD_INMUTABLE'; END IF;
  IF OLD.estado='OBSOLETA' AND NEW.estado<>'OBSOLETA' THEN RAISE EXCEPTION 'PA_GENERACION_NO_REABRIBLE'; END IF;
  RETURN NEW;
END $$;
