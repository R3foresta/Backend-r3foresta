-- PA-T-INT02-B / contrato 5.1 y 8.3. Depende de 068 y 069 CONFIRMADAS.
-- Aditiva: no asigna permisos ni modifica roles, equipo o hechos anteriores.
BEGIN;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='30s';

DO $$
DECLARE v_tabla TEXT;
BEGIN
  FOREACH v_tabla IN ARRAY ARRAY['usuario','subcampania','subcampania_historial','participacion_comando'] LOOP
    IF to_regclass('public.' || v_tabla) IS NULL THEN
      RAISE EXCEPTION 'PA_INT02B_FALTA_DEPENDENCIA: %', v_tabla;
    END IF;
  END LOOP;
  IF NOT EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid='public.usuario'::regclass
                 AND attname='activo' AND atttypid='boolean'::regtype AND NOT attisdropped)
     OR NOT EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid='public.subcampania_historial'::regclass
                    AND attname='metadata' AND atttypid='jsonb'::regtype AND NOT attisdropped) THEN
    RAISE EXCEPTION 'PA_INT02B_CATALOGO_INCOMPATIBLE';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.subcampania_permiso_revision (
  subcampania_id BIGINT NOT NULL REFERENCES public.subcampania(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  usuario_id BIGINT NOT NULL REFERENCES public.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  revision BIGINT NOT NULL CHECK (revision >= 1),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  actualizado_por BIGINT NOT NULL REFERENCES public.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  PRIMARY KEY (subcampania_id, usuario_id)
);
CREATE INDEX IF NOT EXISTS subcampania_permiso_revision_usuario_idx
  ON public.subcampania_permiso_revision(usuario_id, subcampania_id);

CREATE TABLE IF NOT EXISTS public.subcampania_permiso (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subcampania_id BIGINT NOT NULL REFERENCES public.subcampania(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  usuario_id BIGINT NOT NULL REFERENCES public.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  rol_contextual TEXT NOT NULL CHECK (rol_contextual IN ('PLANTADOR','ADMINISTRADOR_SUBCAMPANIA')),
  otorgado_en TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  otorgado_por BIGINT NOT NULL REFERENCES public.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  comando_otorgamiento_id BIGINT NOT NULL REFERENCES public.participacion_comando(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  revocado_en TIMESTAMPTZ,
  revocado_por BIGINT REFERENCES public.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  comando_retiro_id BIGINT REFERENCES public.participacion_comando(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT subcampania_permiso_revision_fk FOREIGN KEY (subcampania_id,usuario_id)
    REFERENCES public.subcampania_permiso_revision(subcampania_id,usuario_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT subcampania_permiso_actor_otorgamiento_fk FOREIGN KEY (comando_otorgamiento_id,otorgado_por)
    REFERENCES public.participacion_comando(id,actor_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT subcampania_permiso_actor_retiro_fk FOREIGN KEY (comando_retiro_id,revocado_por)
    REFERENCES public.participacion_comando(id,actor_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT subcampania_permiso_retiro_chk CHECK (
    (revocado_en IS NULL AND revocado_por IS NULL AND comando_retiro_id IS NULL)
    OR (revocado_en IS NOT NULL AND revocado_por IS NOT NULL AND comando_retiro_id IS NOT NULL
        AND revocado_en >= otorgado_en)
  )
);
CREATE UNIQUE INDEX IF NOT EXISTS subcampania_permiso_un_vigente_idx
  ON public.subcampania_permiso(subcampania_id,usuario_id) WHERE revocado_en IS NULL;
CREATE INDEX IF NOT EXISTS subcampania_permiso_administradores_idx
  ON public.subcampania_permiso(subcampania_id,usuario_id)
  WHERE revocado_en IS NULL AND rol_contextual='ADMINISTRADOR_SUBCAMPANIA';
CREATE INDEX IF NOT EXISTS subcampania_permiso_usuario_vigente_idx
  ON public.subcampania_permiso(usuario_id,subcampania_id) WHERE revocado_en IS NULL;

ALTER TABLE public.subcampania
  ADD COLUMN IF NOT EXISTS participacion_inicializada_en TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS participacion_inicializada_por BIGINT;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.subcampania'::regclass
                 AND conname='subcampania_participacion_inicializada_fk') THEN
    ALTER TABLE public.subcampania ADD CONSTRAINT subcampania_participacion_inicializada_fk
      FOREIGN KEY (participacion_inicializada_por) REFERENCES public.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.subcampania'::regclass
                 AND conname='subcampania_participacion_inicializada_chk') THEN
    ALTER TABLE public.subcampania ADD CONSTRAINT subcampania_participacion_inicializada_chk
      CHECK ((participacion_inicializada_en IS NULL) = (participacion_inicializada_por IS NULL));
  END IF;
END $$;

ALTER TABLE public.subcampania_historial ADD COLUMN IF NOT EXISTS participacion_comando_id BIGINT;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.subcampania_historial'::regclass
                 AND conname='subcampania_historial_participacion_comando_fk') THEN
    ALTER TABLE public.subcampania_historial ADD CONSTRAINT subcampania_historial_participacion_comando_fk
      FOREIGN KEY (participacion_comando_id) REFERENCES public.participacion_comando(id) ON UPDATE RESTRICT ON DELETE RESTRICT;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.subcampania_historial'::regclass
                 AND conname='subcampania_historial_comando_actor_fk') THEN
    ALTER TABLE public.subcampania_historial ADD CONSTRAINT subcampania_historial_comando_actor_fk
      FOREIGN KEY (participacion_comando_id,actor_user_id) REFERENCES public.participacion_comando(id,actor_id)
      ON UPDATE RESTRICT ON DELETE RESTRICT;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.subcampania_historial'::regclass
                 AND conname='subcampania_historial_acceso_chk') THEN
    ALTER TABLE public.subcampania_historial ADD CONSTRAINT subcampania_historial_acceso_chk CHECK (
      tipo_historial::text NOT IN ('PERMISO_OTORGADO','PERMISO_CAMBIADO','PERMISO_RETIRADO','ADMINISTRADOR_REEMPLAZADO')
      OR (participacion_comando_id IS NOT NULL AND actor_user_id IS NOT NULL
          AND estado_origen IS NOT NULL AND estado_destino IS NOT NULL
          AND estado_origen=estado_destino
          AND jsonb_typeof(metadata->'anterior') IS NOT DISTINCT FROM 'array'
          AND jsonb_typeof(metadata->'nuevo') IS NOT DISTINCT FROM 'array'
          AND jsonb_array_length(metadata->'anterior')>0
          AND jsonb_array_length(metadata->'anterior')=jsonb_array_length(metadata->'nuevo'))
    );
  END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS subcampania_historial_comando_acceso_idx
  ON public.subcampania_historial(participacion_comando_id,subcampania_id)
  WHERE tipo_historial IN ('PERMISO_OTORGADO','PERMISO_CAMBIADO','PERMISO_RETIRADO','ADMINISTRADOR_REEMPLAZADO');

-- Una revision no se borra/recrea y una vigencia cerrada no se rehabilita.
CREATE OR REPLACE FUNCTION public.pa_permiso_revision_proteger() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public AS $$
BEGIN
  IF TG_OP IN ('DELETE','TRUNCATE') THEN
    RAISE EXCEPTION 'PA_REVISION_ESTABLE_NO_BORRABLE' USING ERRCODE='23514';
  ELSIF TG_OP='INSERT' THEN
    IF NEW.revision <> 1 THEN RAISE EXCEPTION 'PA_PRIMERA_REVISION_DEBE_SER_UNO' USING ERRCODE='23514'; END IF;
  ELSIF NEW.subcampania_id <> OLD.subcampania_id OR NEW.usuario_id <> OLD.usuario_id
     OR NEW.revision <> OLD.revision + 1 OR NEW.actualizado_en < OLD.actualizado_en THEN
    RAISE EXCEPTION 'PA_REVISION_DEBE_AVANZAR_UNA_VEZ' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS pa_permiso_revision_proteger ON public.subcampania_permiso_revision;
CREATE TRIGGER pa_permiso_revision_proteger BEFORE INSERT OR UPDATE OR DELETE
  ON public.subcampania_permiso_revision FOR EACH ROW EXECUTE FUNCTION public.pa_permiso_revision_proteger();
DROP TRIGGER IF EXISTS pa_permiso_revision_no_truncate ON public.subcampania_permiso_revision;
CREATE TRIGGER pa_permiso_revision_no_truncate BEFORE TRUNCATE
  ON public.subcampania_permiso_revision FOR EACH STATEMENT EXECUTE FUNCTION public.pa_permiso_revision_proteger();

CREATE OR REPLACE FUNCTION public.pa_permiso_vigencia_proteger() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public AS $$
BEGIN
  IF TG_OP IN ('DELETE','TRUNCATE') THEN
    RAISE EXCEPTION 'PA_VIGENCIA_NO_BORRABLE' USING ERRCODE='23514';
  END IF;
  IF ROW(NEW.id,NEW.subcampania_id,NEW.usuario_id,NEW.rol_contextual,NEW.otorgado_en,
         NEW.otorgado_por,NEW.comando_otorgamiento_id) IS DISTINCT FROM
     ROW(OLD.id,OLD.subcampania_id,OLD.usuario_id,OLD.rol_contextual,OLD.otorgado_en,
         OLD.otorgado_por,OLD.comando_otorgamiento_id)
     OR OLD.revocado_en IS NOT NULL THEN
    RAISE EXCEPTION 'PA_VIGENCIA_INMUTABLE_O_CERRADA' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS pa_permiso_vigencia_proteger ON public.subcampania_permiso;
CREATE TRIGGER pa_permiso_vigencia_proteger BEFORE UPDATE OR DELETE
  ON public.subcampania_permiso FOR EACH ROW EXECUTE FUNCTION public.pa_permiso_vigencia_proteger();
DROP TRIGGER IF EXISTS pa_permiso_vigencia_no_truncate ON public.subcampania_permiso;
CREATE TRIGGER pa_permiso_vigencia_no_truncate BEFORE TRUNCATE
  ON public.subcampania_permiso FOR EACH STATEMENT EXECUTE FUNCTION public.pa_permiso_vigencia_proteger();

CREATE OR REPLACE FUNCTION public.pa_participacion_marca_proteger() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public AS $$
BEGIN
  IF OLD.participacion_inicializada_en IS NOT NULL AND
     ROW(NEW.participacion_inicializada_en,NEW.participacion_inicializada_por) IS DISTINCT FROM
     ROW(OLD.participacion_inicializada_en,OLD.participacion_inicializada_por) THEN
    RAISE EXCEPTION 'PA_INICIALIZACION_INMUTABLE' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS pa_participacion_marca_proteger ON public.subcampania;
CREATE TRIGGER pa_participacion_marca_proteger BEFORE UPDATE ON public.subcampania
  FOR EACH ROW EXECUTE FUNCTION public.pa_participacion_marca_proteger();

