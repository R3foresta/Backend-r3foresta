-- Cerrar grants de tabla, columna, secuencia y todas las sobrecargas sensibles.
-- El SELECT legado de subcampania se conserva; sus escrituras usan backend privado.
DO $$
DECLARE v_tabla TEXT; v_columna RECORD; v_secuencia TEXT; v_funcion RECORD; v_rol TEXT;
BEGIN
  FOREACH v_tabla IN ARRAY ARRAY['subcampania_permiso_revision','subcampania_permiso','subcampania_historial'] LOOP
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC,anon,authenticated,service_role',v_tabla);
    FOR v_columna IN SELECT attname FROM pg_attribute WHERE attrelid=to_regclass('public.'||v_tabla)
                    AND attnum>0 AND NOT attisdropped LOOP
      EXECUTE format('REVOKE ALL (%I) ON TABLE public.%I FROM PUBLIC,anon,authenticated,service_role',v_columna.attname,v_tabla);
    END LOOP;
    IF v_tabla='subcampania_permiso_revision' THEN
      EXECUTE format('GRANT SELECT,INSERT,UPDATE ON TABLE public.%I TO service_role',v_tabla);
    ELSIF v_tabla='subcampania_permiso' THEN
      EXECUTE format('GRANT SELECT,INSERT,UPDATE ON TABLE public.%I TO service_role',v_tabla);
    ELSE
      EXECUTE format('GRANT SELECT,INSERT ON TABLE public.%I TO service_role',v_tabla);
    END IF;
    v_secuencia := NULL;
    IF EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid=to_regclass('public.'||v_tabla)
               AND attname='id' AND NOT attisdropped) THEN
      v_secuencia := pg_get_serial_sequence('public.'||v_tabla,'id');
    END IF;
    IF v_secuencia IS NOT NULL THEN
      EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC,anon,authenticated,service_role',v_secuencia);
      EXECUTE format('GRANT USAGE,SELECT ON SEQUENCE %s TO service_role',v_secuencia);
    END IF;
  END LOOP;
  REVOKE INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER ON public.subcampania FROM PUBLIC,anon,authenticated;
  IF current_setting('server_version_num')::integer >= 170000 THEN
    EXECUTE 'REVOKE MAINTAIN ON public.subcampania FROM PUBLIC,anon,authenticated';
  END IF;
  FOR v_columna IN SELECT attname FROM pg_attribute WHERE attrelid='public.subcampania'::regclass
                  AND attnum>0 AND NOT attisdropped LOOP
    EXECUTE format('REVOKE INSERT (%I),UPDATE (%I),REFERENCES (%I) ON public.subcampania FROM PUBLIC,anon,authenticated',
                   v_columna.attname,v_columna.attname,v_columna.attname);
  END LOOP;
  GRANT SELECT,INSERT,UPDATE ON public.subcampania TO service_role;
  FOR v_funcion IN SELECT p.oid::regprocedure AS firma FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
    WHERE n.nspname='public' AND p.proname IN ('pa_permiso_revision_proteger','pa_permiso_vigencia_proteger',
      'pa_participacion_marca_proteger','fn_subcampania_historial_prevent_mutation') LOOP
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC,anon,authenticated,service_role',v_funcion.firma);
  END LOOP;
  FOREACH v_rol IN ARRAY ARRAY['anon','authenticated'] LOOP
    FOREACH v_tabla IN ARRAY ARRAY['subcampania_permiso_revision','subcampania_permiso','subcampania_historial'] LOOP
      IF has_table_privilege(v_rol,'public.'||v_tabla,'SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER')
         OR has_any_column_privilege(v_rol,'public.'||v_tabla,'SELECT,INSERT,UPDATE,REFERENCES') THEN
        RAISE EXCEPTION 'PA_INT02B_PRIVILEGIO_HEREDADO: %/%',v_rol,v_tabla;
      END IF;
      IF current_setting('server_version_num')::integer >= 170000
         AND has_table_privilege(v_rol,'public.'||v_tabla,'MAINTAIN') THEN
        RAISE EXCEPTION 'PA_INT02B_MANTENIMIENTO_HEREDADO: %/%',v_rol,v_tabla;
      END IF;
    END LOOP;
    IF has_table_privilege(v_rol,'public.subcampania','INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER')
       OR has_any_column_privilege(v_rol,'public.subcampania','INSERT,UPDATE,REFERENCES') THEN
      RAISE EXCEPTION 'PA_INT02B_ESCRITURA_SUBCAMPANIA_HEREDADA: %',v_rol;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
      WHERE n.nspname='public' AND p.proname IN ('pa_permiso_revision_proteger','pa_permiso_vigencia_proteger',
        'pa_participacion_marca_proteger','fn_subcampania_historial_prevent_mutation')
        AND has_function_privilege(v_rol,p.oid,'EXECUTE')) THEN
      RAISE EXCEPTION 'PA_INT02B_HELPER_EXECUTE_HEREDADO: %',v_rol;
    END IF;
    -- Una vista propiedad de otro rol o un definer podria eludir ACL/RLS.
    IF EXISTS (SELECT 1 FROM pg_depend d JOIN pg_rewrite w ON w.oid=d.objid
      JOIN pg_class vista ON vista.oid=w.ev_class
      WHERE d.classid='pg_rewrite'::regclass AND d.refclassid='pg_class'::regclass
        AND vista.relkind IN ('v','m') AND d.refobjid IN ('public.subcampania_permiso'::regclass,
          'public.subcampania_permiso_revision'::regclass,'public.subcampania_historial'::regclass)
        AND has_any_column_privilege(v_rol,vista.oid,'SELECT')) THEN
      RAISE EXCEPTION 'PA_INT02B_VISTA_PRIVADA_PUBLICA: %',v_rol;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
      WHERE n.nspname='public' AND p.prosecdef
        AND p.prosrc ~* '(subcampania_permiso|subcampania_historial|participacion_comando)'
        AND has_function_privilege(v_rol,p.oid,'EXECUTE')) THEN
      RAISE EXCEPTION 'PA_INT02B_DEFINER_PRIVADO_PUBLICO: %',v_rol;
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_policy WHERE polrelid IN ('public.subcampania_permiso'::regclass,
      'public.subcampania_permiso_revision'::regclass)
      AND (0::oid=ANY(polroles) OR EXISTS (SELECT 1 FROM pg_roles
           WHERE rolname IN ('anon','authenticated') AND oid=ANY(polroles)))) THEN
    RAISE EXCEPTION 'PA_INT02B_POLITICA_PUBLICA_INCOMPATIBLE';
  END IF;
END $$;

