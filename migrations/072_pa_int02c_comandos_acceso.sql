-- PA-T-INT02-C BE04/BE05. Infraestructura común de comandos sin fotos.
-- Depende de 064 y 068–071. No instala REGISTRAR_PLANTACION_INICIAL (INT03-A)
-- ni acredita las carreras con stock/registro y cierre pendientes de INT02-D.
-- Ejecutar solo después del cotejo del catálogo; no ejecuta comandos al instalar.
BEGIN;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='30s';

CREATE TABLE IF NOT EXISTS public.usuario_autoridad_historial (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comando_id BIGINT NOT NULL REFERENCES public.participacion_comando(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  usuario_id BIGINT NOT NULL REFERENCES public.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  actor_id BIGINT NOT NULL REFERENCES public.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  evento TEXT NOT NULL CHECK(evento IN ('ROL_CAMBIADO','CUENTA_INACTIVADA')),
  rol_anterior public.rol_usuario NOT NULL,
  rol_nuevo public.rol_usuario NOT NULL,
  activo_anterior BOOLEAN NOT NULL,
  activo_nuevo BOOLEAN NOT NULL,
  revision_anterior BIGINT NOT NULL CHECK(revision_anterior>=0),
  revision_nueva BIGINT NOT NULL CHECK(revision_nueva=revision_anterior+1),
  motivo TEXT NOT NULL CHECK(char_length(motivo) BETWEEN 3 AND 1000 AND motivo=normalize(btrim(motivo),NFC)),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  UNIQUE(comando_id,usuario_id),
  FOREIGN KEY(comando_id,actor_id) REFERENCES public.participacion_comando(id,actor_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CHECK((evento='ROL_CAMBIADO' AND rol_anterior<>rol_nuevo AND activo_anterior AND activo_nuevo)
     OR (evento='CUENTA_INACTIVADA' AND rol_anterior=rol_nuevo AND activo_anterior AND NOT activo_nuevo))
);
-- IF NOT EXISTS no certifica una tabla preexistente de otra forma.
DO $$ DECLARE v RECORD; BEGIN
  FOR v IN SELECT * FROM (VALUES
    ('id','bigint',true),('comando_id','bigint',true),('usuario_id','bigint',true),
    ('actor_id','bigint',true),('evento','text',true),('rol_anterior','public.rol_usuario',true),
    ('rol_nuevo','public.rol_usuario',true),('activo_anterior','boolean',true),('activo_nuevo','boolean',true),
    ('revision_anterior','bigint',true),('revision_nueva','bigint',true),('motivo','text',true),
    ('creado_en','timestamp with time zone',true)
  ) AS esperado(columna,tipo,obligatoria) LOOP
    IF NOT EXISTS(SELECT 1 FROM pg_attribute WHERE attrelid='public.usuario_autoridad_historial'::regclass
      AND attname=v.columna AND atttypid=v.tipo::regtype AND attnotnull=v.obligatoria AND NOT attisdropped) THEN
      RAISE EXCEPTION 'PA_INT02C_AUDITORIA_COLUMNA_INCOMPATIBLE: %',v.columna;
    END IF;
  END LOOP;
  IF (SELECT count(*) FROM pg_constraint WHERE conrelid='public.usuario_autoridad_historial'::regclass
    AND contype='f' AND convalidated AND confupdtype='r' AND confdeltype='r')<>4
    OR NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='public.usuario_autoridad_historial'::regclass
      AND contype='p' AND convalidated)
    OR NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='public.usuario_autoridad_historial'::regclass
      AND contype='u' AND convalidated) THEN
    RAISE EXCEPTION 'PA_INT02C_AUDITORIA_RESTRICCIONES_INCOMPATIBLES';
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS usuario_autoridad_historial_usuario_fecha_idx
  ON public.usuario_autoridad_historial(usuario_id,creado_en,id);
DROP TRIGGER IF EXISTS usuario_autoridad_historial_inmutable ON public.usuario_autoridad_historial;
CREATE TRIGGER usuario_autoridad_historial_inmutable BEFORE UPDATE OR DELETE OR TRUNCATE
  ON public.usuario_autoridad_historial FOR EACH STATEMENT
  EXECUTE FUNCTION public.fn_subcampania_historial_prevent_mutation();
ALTER TABLE public.usuario_autoridad_historial ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.pa_c_error(
  p_codigo TEXT,p_mensaje TEXT,p_reintento TEXT DEFAULT 'NUEVA_CONFIRMACION',
  p_campos JSONB DEFAULT '[]',p_ambitos JSONB DEFAULT '[]'
) RETURNS JSONB LANGUAGE sql IMMUTABLE SECURITY INVOKER SET search_path=pg_catalog,public AS $$
  SELECT jsonb_build_object('codigo',p_codigo,'mensaje',p_mensaje,'campos',p_campos,
    'ambitos',p_ambitos,'reintento',p_reintento)
$$;
CREATE OR REPLACE FUNCTION public.pa_c_fuera(
  p_http INTEGER,p_codigo TEXT,p_mensaje TEXT,p_comando_id UUID,
  p_reintento TEXT DEFAULT 'NO_APLICA'
) RETURNS JSONB LANGUAGE sql IMMUTABLE SECURITY INVOKER SET search_path=pg_catalog,public AS $$
  SELECT jsonb_build_object('http_status',p_http,'body',jsonb_build_object(
    'error',public.pa_c_error(p_codigo,p_mensaje,p_reintento),
    'comando_id',p_comando_id,'resultado_concluyente',false))
$$;
CREATE OR REPLACE FUNCTION public.pa_c_recibo(p_comando public.participacion_comando,p_get BOOLEAN DEFAULT false)
RETURNS JSONB LANGUAGE sql STABLE SECURITY INVOKER SET search_path=pg_catalog,public AS $$
  SELECT jsonb_build_object('http_status',CASE WHEN p_get THEN 200 ELSE p_comando.http_terminal END,
    'body',jsonb_build_object('comando_id',p_comando.comando_id,'operacion',p_comando.operacion,
      'estado',p_comando.estado,'resultado',p_comando.resultado,'error',p_comando.error,
      'finalizado_en',to_char(p_comando.finalizado_en AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US"Z"')))
$$;
CREATE OR REPLACE FUNCTION public.pa_c_decimal(p_valor JSONB,p_cero BOOLEAN DEFAULT false)
RETURNS BOOLEAN LANGUAGE sql IMMUTABLE SECURITY INVOKER SET search_path=pg_catalog,public AS $$
  SELECT COALESCE(jsonb_typeof(p_valor)='string' AND
    (p_valor#>>'{}') ~ CASE WHEN p_cero THEN '^(0|[1-9][0-9]*)$' ELSE '^[1-9][0-9]*$' END AND
    (length(p_valor#>>'{}')<19 OR (length(p_valor#>>'{}')=19 AND (p_valor#>>'{}')<='9223372036854775807')),false)
$$;
CREATE OR REPLACE FUNCTION public.pa_c_canon_coincide(p_canon TEXT,p_payload JSONB)
RETURNS BOOLEAN LANGUAGE plpgsql IMMUTABLE SECURITY INVOKER SET search_path=pg_catalog,public AS $$
BEGIN
  RETURN COALESCE(p_canon::jsonb=p_payload,false);
EXCEPTION WHEN invalid_text_representation THEN RETURN false;
END $$;

CREATE OR REPLACE FUNCTION public.pa_acceso_ejecutar(
  p_actor_id BIGINT,p_auth_id TEXT,p_operacion TEXT,p_comando_id UUID,
  p_payload JSONB,p_contenido_canonico TEXT
) RETURNS JSONB LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public AS $$
DECLARE
  v_actor public.usuario%ROWTYPE; v_destino public.usuario%ROWTYPE;
  v_sub public.subcampania%ROWTYPE; v_comando public.participacion_comando%ROWTYPE;
  v_ambito JSONB; v_usuario JSONB; v_plan JSONB:='[]'; v_usuarios JSONB;
  v_payload JSONB; v_resultado JSONB; v_replay JSONB; v_detalle TEXT; v_error JSONB;
  v_anterior JSONB; v_nuevo JSONB; v_huella BYTEA; v_fecha TIMESTAMPTZ;
  v_id BIGINT; v_destino_id BIGINT; v_entrante_id BIGINT; v_usuario_id BIGINT;
  v_revision BIGINT; v_revision_esperada BIGINT; v_vigencia_id BIGINT;
  v_permiso TEXT; v_permiso_nuevo TEXT; v_tipo TEXT; v_reemplazo BOOLEAN;
  v_global BOOLEAN; v_cambio BOOLEAN; v_http INTEGER;
BEGIN
  PERFORM set_config('lock_timeout','5s',true);
  v_reemplazo:=p_operacion='REEMPLAZAR_ADMINISTRADOR';
  IF p_operacion IS NULL OR p_operacion NOT IN ('OTORGAR_PLANTADOR','RETIRAR_PLANTADOR',
    'DESIGNAR_ADMINISTRADOR','CAMBIAR_ADMINISTRADOR_A_PLANTADOR','RETIRAR_ADMINISTRADOR','REEMPLAZAR_ADMINISTRADOR')
    OR p_comando_id IS NULL OR p_comando_id::text !~ '^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
    OR jsonb_typeof(p_payload) IS DISTINCT FROM 'object' THEN
    RETURN public.pa_c_fuera(422,'ENTRADA_INVALIDA','La entrada no es válida.',p_comando_id);
  END IF;
  IF (p_payload-CASE WHEN v_reemplazo THEN ARRAY['usuario_saliente_id','usuario_reemplazo_id','tratamiento_saliente','ambitos']
      ELSE ARRAY['usuario_destino_id','ambitos'] END)<>'{}'::jsonb THEN
    RETURN public.pa_c_fuera(422,'CAMPO_NO_PERMITIDO','Hay campos no permitidos.',p_comando_id);
  END IF;
  IF (v_reemplazo AND (NOT public.pa_c_decimal(p_payload->'usuario_saliente_id')
    OR NOT public.pa_c_decimal(p_payload->'usuario_reemplazo_id')
    OR p_payload->>'usuario_saliente_id'=p_payload->>'usuario_reemplazo_id'
    OR COALESCE(p_payload->>'tratamiento_saliente','') NOT IN ('PLANTADOR','SIN_ACCESO')))
    OR (NOT v_reemplazo AND NOT public.pa_c_decimal(p_payload->'usuario_destino_id'))
    OR jsonb_typeof(p_payload->'ambitos') IS DISTINCT FROM 'array' THEN
    RETURN public.pa_c_fuera(422,'ENTRADA_INVALIDA','La selección no es válida.',p_comando_id);
  END IF;
  IF jsonb_array_length(p_payload->'ambitos') NOT BETWEEN 1 AND 100 THEN
    RETURN public.pa_c_fuera(422,'ENTRADA_INVALIDA','La selección no es válida.',p_comando_id);
  END IF;
  FOR v_ambito IN SELECT value FROM jsonb_array_elements(p_payload->'ambitos') LOOP
    IF jsonb_typeof(v_ambito) IS DISTINCT FROM 'object' THEN
      RETURN public.pa_c_fuera(422,'ENTRADA_INVALIDA','La selección no es válida.',p_comando_id);
    END IF;
    IF (v_ambito-CASE WHEN v_reemplazo THEN ARRAY['subcampania_id','revision_saliente_esperada','revision_reemplazo_esperada']
      ELSE ARRAY['subcampania_id','revision_esperada'] END)<>'{}'::jsonb THEN
      RETURN public.pa_c_fuera(422,'CAMPO_NO_PERMITIDO','Hay campos no permitidos.',p_comando_id);
    END IF;
    IF NOT public.pa_c_decimal(v_ambito->'subcampania_id')
      OR (v_reemplazo AND (NOT public.pa_c_decimal(v_ambito->'revision_saliente_esperada',true)
        OR NOT public.pa_c_decimal(v_ambito->'revision_reemplazo_esperada',true)))
      OR (NOT v_reemplazo AND NOT public.pa_c_decimal(v_ambito->'revision_esperada',true)) THEN
      RETURN public.pa_c_fuera(422,'ENTRADA_INVALIDA','La selección no es válida.',p_comando_id);
    END IF;
  END LOOP;
  IF EXISTS(SELECT 1 FROM jsonb_array_elements(p_payload->'ambitos') a GROUP BY a->>'subcampania_id' HAVING count(*)>1) THEN
    RETURN public.pa_c_fuera(422,'ENTRADA_INVALIDA','La selección contiene ámbitos duplicados.',p_comando_id);
  END IF;
  SELECT (p_payload-'ambitos')||jsonb_build_object('ambitos',jsonb_agg(a ORDER BY (a->>'subcampania_id')::bigint))
    INTO v_payload FROM jsonb_array_elements(p_payload->'ambitos') a;
  IF NOT public.pa_c_canon_coincide(p_contenido_canonico,v_payload) THEN
    RETURN public.pa_c_fuera(422,'ENTRADA_INVALIDA','El contenido canónico no corresponde a la intención.',p_comando_id);
  END IF;
  v_huella:=sha256(convert_to('PA-COMANDO/1'||chr(10)||p_operacion||chr(10)||p_contenido_canonico,'UTF8'));
  -- El replay propio precede los locks de dominio y la autorización nueva.
  v_replay:=public.pa_c_replay(p_actor_id,p_auth_id,p_operacion,p_comando_id,v_huella);
  IF v_replay IS NOT NULL THEN RETURN v_replay; END IF;
  v_destino_id:=(v_payload->>CASE WHEN v_reemplazo THEN 'usuario_saliente_id' ELSE 'usuario_destino_id' END)::bigint;
  IF v_reemplazo THEN v_entrante_id:=(v_payload->>'usuario_reemplazo_id')::bigint; END IF;
  -- Todas las cuentas ASC, luego todos los ámbitos ASC. Sin upgrades SHARE.
  FOR v_usuario_id IN SELECT DISTINCT n FROM unnest(ARRAY[p_actor_id,v_destino_id,v_entrante_id]) n
    WHERE n IS NOT NULL ORDER BY n LOOP
    PERFORM 1 FROM public.usuario WHERE id=v_usuario_id FOR SHARE;
  END LOOP;
  SELECT * INTO v_actor FROM public.usuario WHERE id=p_actor_id AND auth_id=p_auth_id;
  IF NOT FOUND THEN RETURN public.pa_c_fuera(401,'SESION_INVALIDA','La sesión no es válida.',p_comando_id,'RECUPERAR_SESION'); END IF;
  IF NOT v_actor.activo THEN RETURN public.pa_c_fuera(403,'CUENTA_INACTIVA','La cuenta no está activa.',p_comando_id); END IF;
  FOR v_id IN SELECT (a->>'subcampania_id')::bigint FROM jsonb_array_elements(v_payload->'ambitos') a ORDER BY 1 LOOP
    PERFORM 1 FROM public.subcampania WHERE id=v_id FOR UPDATE;
  END LOOP;
  -- Exclusión de identidad, etapa 5. No publica una fila EN_CURSO/PREPARADO.
  PERFORM pg_advisory_xact_lock(hashtextextended('pa:comando:'||p_actor_id||':'||p_operacion||':'||p_comando_id,0));
  SELECT * INTO v_comando FROM public.participacion_comando
    WHERE actor_id=p_actor_id AND operacion=p_operacion AND comando_id=p_comando_id FOR UPDATE;
  IF FOUND THEN
    IF v_comando.huella IS DISTINCT FROM v_huella THEN
      RETURN public.pa_c_fuera(409,'COMANDO_REUTILIZADO','La clave ya corresponde a otro contenido.',p_comando_id,'MISMA_CLAVE');
    END IF;
    RETURN public.pa_c_recibo(v_comando);
  END IF;
  v_global:=v_actor.rol::text='ADMIN';
  BEGIN
    IF NOT v_global AND p_operacion NOT IN ('OTORGAR_PLANTADOR','RETIRAR_PLANTADOR') THEN
      PERFORM public.pa_c_rechazar(403,'CAPACIDAD_INSUFICIENTE','No dispone de esta capacidad.');
    END IF;
    -- Primero autorizar el conjunto; ninguna respuesta expone ámbito ajeno.
    FOR v_ambito IN SELECT value FROM jsonb_array_elements(v_payload->'ambitos') LOOP
      v_id:=(v_ambito->>'subcampania_id')::bigint;
      IF NOT v_global AND NOT EXISTS(SELECT 1 FROM public.subcampania_permiso
        WHERE subcampania_id=v_id AND usuario_id=p_actor_id AND rol_contextual='ADMINISTRADOR_SUBCAMPANIA' AND revocado_en IS NULL) THEN
        PERFORM public.pa_c_rechazar(403,'CAPACIDAD_INSUFICIENTE','No dispone de esta capacidad en la selección.');
      END IF;
    END LOOP;
    FOR v_ambito IN SELECT value FROM jsonb_array_elements(v_payload->'ambitos') LOOP
      v_id:=(v_ambito->>'subcampania_id')::bigint;
      IF NOT EXISTS(SELECT 1 FROM public.subcampania WHERE id=v_id AND deleted_at IS NULL) THEN
        PERFORM public.pa_c_rechazar(404,'RECURSO_NO_VISIBLE','El recurso no está disponible.');
      END IF;
    END LOOP;
    SELECT * INTO v_destino FROM public.usuario WHERE id=v_destino_id;
    IF NOT FOUND THEN PERFORM public.pa_c_rechazar(404,'RECURSO_NO_VISIBLE','El recurso no está disponible.'); END IF;
    IF p_operacion IN ('OTORGAR_PLANTADOR','DESIGNAR_ADMINISTRADOR') AND NOT v_destino.activo THEN
      PERFORM public.pa_c_rechazar(409,'DESTINO_INACTIVO','La cuenta destino no está activa.');
    END IF;
    IF v_reemplazo THEN
      IF NOT EXISTS(SELECT 1 FROM public.usuario WHERE id=v_entrante_id) THEN
        PERFORM public.pa_c_rechazar(404,'RECURSO_NO_VISIBLE','El recurso no está disponible.');
      END IF;
      IF NOT EXISTS(SELECT 1 FROM public.usuario WHERE id=v_entrante_id AND activo) THEN
        PERFORM public.pa_c_rechazar(409,'DESTINO_INACTIVO','La cuenta reemplazo no está activa.');
      END IF;
    END IF;
    -- Validar todas las revisiones y continuidad antes del primer efecto.
    FOR v_ambito IN SELECT value FROM jsonb_array_elements(v_payload->'ambitos') LOOP
      v_id:=(v_ambito->>'subcampania_id')::bigint;
      SELECT * INTO STRICT v_sub FROM public.subcampania WHERE id=v_id;
      IF v_sub.estado::text='PAUSADA' OR
        (p_operacion IN ('OTORGAR_PLANTADOR','DESIGNAR_ADMINISTRADOR') AND v_sub.estado::text NOT IN ('BORRADOR','ACTIVA')) THEN
        PERFORM public.pa_c_rechazar(409,'ESTADO_NO_ADMITE_ACCESO','El estado no admite esta acción.');
      END IF;
      v_usuarios:='[]';
      FOR v_usuario_id IN SELECT n FROM unnest(ARRAY[v_destino_id,v_entrante_id]) n WHERE n IS NOT NULL ORDER BY n LOOP
        SELECT coalesce((SELECT revision FROM public.subcampania_permiso_revision
          WHERE subcampania_id=v_id AND usuario_id=v_usuario_id),0) INTO v_revision;
        v_revision_esperada:=(v_ambito->>CASE WHEN NOT v_reemplazo THEN 'revision_esperada'
          WHEN v_usuario_id=v_destino_id THEN 'revision_saliente_esperada' ELSE 'revision_reemplazo_esperada' END)::bigint;
        IF v_revision<>v_revision_esperada THEN
          PERFORM public.pa_c_rechazar(409,'REVISION_OBSOLETA','La revisión cambió; revise la selección.');
        END IF;
        SELECT rol_contextual,id INTO v_permiso,v_vigencia_id FROM public.subcampania_permiso
          WHERE subcampania_id=v_id AND usuario_id=v_usuario_id AND revocado_en IS NULL;
        v_permiso_nuevo:=CASE p_operacion
          WHEN 'OTORGAR_PLANTADOR' THEN 'PLANTADOR'
          WHEN 'RETIRAR_PLANTADOR' THEN NULL
          WHEN 'DESIGNAR_ADMINISTRADOR' THEN 'ADMINISTRADOR_SUBCAMPANIA'
          WHEN 'CAMBIAR_ADMINISTRADOR_A_PLANTADOR' THEN 'PLANTADOR'
          WHEN 'RETIRAR_ADMINISTRADOR' THEN NULL
          ELSE CASE WHEN v_usuario_id=v_entrante_id THEN 'ADMINISTRADOR_SUBCAMPANIA'
            WHEN v_payload->>'tratamiento_saliente'='PLANTADOR' THEN 'PLANTADOR' ELSE NULL END END;
        IF (p_operacion IN ('OTORGAR_PLANTADOR','RETIRAR_PLANTADOR') AND v_permiso='ADMINISTRADOR_SUBCAMPANIA')
          OR (p_operacion IN ('CAMBIAR_ADMINISTRADOR_A_PLANTADOR','RETIRAR_ADMINISTRADOR','REEMPLAZAR_ADMINISTRADOR')
            AND v_usuario_id=v_destino_id AND v_permiso IS DISTINCT FROM 'ADMINISTRADOR_SUBCAMPANIA') THEN
          PERFORM public.pa_c_rechazar(409,'TIPO_PERMISO_INCOMPATIBLE','El permiso actual no admite esta acción.');
        END IF;
        IF p_operacion IN ('CAMBIAR_ADMINISTRADOR_A_PLANTADOR','RETIRAR_ADMINISTRADOR') AND NOT EXISTS(
          SELECT 1 FROM public.subcampania_permiso p JOIN public.usuario u ON u.id=p.usuario_id
          WHERE p.subcampania_id=v_id AND p.usuario_id<>v_destino_id AND p.revocado_en IS NULL
            AND p.rol_contextual='ADMINISTRADOR_SUBCAMPANIA' AND u.activo) THEN
          PERFORM public.pa_c_rechazar(409,'ULTIMO_ADMINISTRADOR_CONTEXTUAL','Debe permanecer un administrador contextual activo.');
        END IF;
        v_cambio:=v_permiso IS DISTINCT FROM v_permiso_nuevo;
        IF v_cambio AND v_revision=9223372036854775807 THEN
          PERFORM public.pa_c_rechazar(409,'REVISION_OBSOLETA','La revisión no admite nuevos cambios.');
        END IF;
        v_usuarios:=v_usuarios||jsonb_build_array(jsonb_build_object('usuario_id',v_usuario_id::text,
          'permiso_anterior',v_permiso,'permiso_nuevo',v_permiso_nuevo,'revision_anterior',v_revision::text,
          'revision_nueva',(v_revision+CASE WHEN v_cambio THEN 1 ELSE 0 END)::text,
          'cambio',CASE WHEN v_cambio THEN 'CAMBIO_APLICADO' ELSE 'SIN_CAMBIOS' END,
          'conserva_acceso_global',(SELECT rol::text='ADMIN' AND activo FROM public.usuario WHERE id=v_usuario_id),
          '_vigencia_anterior',v_vigencia_id::text));
      END LOOP;
      v_plan:=v_plan||jsonb_build_array(jsonb_build_object('subcampania_id',v_id::text,'usuarios',v_usuarios));
    END LOOP;
    SELECT jsonb_build_object('tipo','ACCESO','cambios',jsonb_agg(jsonb_build_object(
      'subcampania_id',a->>'subcampania_id','usuarios',
      (SELECT jsonb_agg(u-'_vigencia_anterior' ORDER BY (u->>'usuario_id')::bigint) FROM jsonb_array_elements(a->'usuarios') u))
      ORDER BY (a->>'subcampania_id')::bigint)) INTO v_resultado FROM jsonb_array_elements(v_plan) a;
    v_fecha:=clock_timestamp();
    INSERT INTO public.participacion_comando(actor_id,operacion,comando_id,huella,estado,resultado,http_terminal,creado_en,finalizado_en)
    VALUES(p_actor_id,p_operacion,p_comando_id,v_huella,'CONFIRMADO',v_resultado,200,v_fecha,v_fecha)
    ON CONFLICT(actor_id,operacion,comando_id) DO NOTHING RETURNING * INTO v_comando;
    IF NOT FOUND THEN
      SELECT * INTO STRICT v_comando FROM public.participacion_comando
        WHERE actor_id=p_actor_id AND operacion=p_operacion AND comando_id=p_comando_id FOR UPDATE;
      IF v_comando.huella IS DISTINCT FROM v_huella THEN
        RETURN public.pa_c_fuera(409,'COMANDO_REUTILIZADO','La clave ya corresponde a otro contenido.',p_comando_id,'MISMA_CLAVE');
      END IF;
      RETURN public.pa_c_recibo(v_comando);
    END IF;
    FOR v_ambito IN SELECT value FROM jsonb_array_elements(v_plan) LOOP
      v_id:=(v_ambito->>'subcampania_id')::bigint;
      SELECT * INTO STRICT v_sub FROM public.subcampania WHERE id=v_id;
      v_anterior:='[]'; v_nuevo:='[]'; v_cambio:=false;
      -- Reemplazo aplica primero al entrante aun si su ID es mayor.
      FOR v_usuario IN SELECT value FROM jsonb_array_elements(v_ambito->'usuarios')
        ORDER BY CASE WHEN v_reemplazo AND (value->>'usuario_id')::bigint=v_entrante_id THEN 0 ELSE 1 END,
          (value->>'usuario_id')::bigint LOOP
        v_usuario_id:=(v_usuario->>'usuario_id')::bigint;
        v_vigencia_id:=(v_usuario->>'_vigencia_anterior')::bigint;
        IF v_usuario->>'cambio'='CAMBIO_APLICADO' THEN
          v_cambio:=true;
          v_vigencia_id:=public.pa_c_permiso_aplicar(p_actor_id,v_comando.id,v_id,v_usuario_id,v_usuario->>'permiso_nuevo',v_fecha);
        END IF;
        v_anterior:=v_anterior||jsonb_build_array(jsonb_build_object('usuario_id',v_usuario_id::text,
          'permiso',v_usuario->'permiso_anterior','revision',v_usuario->>'revision_anterior','vigencia_id',v_usuario->'_vigencia_anterior'));
        v_nuevo:=v_nuevo||jsonb_build_array(jsonb_build_object('usuario_id',v_usuario_id::text,
          'permiso',v_usuario->'permiso_nuevo','revision',v_usuario->>'revision_nueva','vigencia_id',v_vigencia_id::text));
      END LOOP;
      IF v_cambio THEN
        v_tipo:=CASE p_operacion WHEN 'REEMPLAZAR_ADMINISTRADOR' THEN 'ADMINISTRADOR_REEMPLAZADO'
          WHEN 'RETIRAR_PLANTADOR' THEN 'PERMISO_RETIRADO' WHEN 'RETIRAR_ADMINISTRADOR' THEN 'PERMISO_RETIRADO'
          ELSE CASE WHEN EXISTS(SELECT 1 FROM jsonb_array_elements(v_ambito->'usuarios') u WHERE u->>'permiso_anterior' IS NOT NULL)
            THEN 'PERMISO_CAMBIADO' ELSE 'PERMISO_OTORGADO' END END;
        INSERT INTO public.subcampania_historial(subcampania_id,tipo_historial,estado_origen,estado_destino,
          metadata,actor_user_id,created_at,participacion_comando_id)
        VALUES(v_id,v_tipo::public.tipo_historial_subcampania,v_sub.estado,v_sub.estado,
          jsonb_build_object('anterior',(SELECT jsonb_agg(u ORDER BY (u->>'usuario_id')::bigint) FROM jsonb_array_elements(v_anterior) u),
            'nuevo',(SELECT jsonb_agg(u ORDER BY (u->>'usuario_id')::bigint) FROM jsonb_array_elements(v_nuevo) u)),p_actor_id,v_fecha,v_comando.id);
        IF p_operacion IN ('DESIGNAR_ADMINISTRADOR','REEMPLAZAR_ADMINISTRADOR') AND v_sub.participacion_inicializada_en IS NULL THEN
          UPDATE public.subcampania SET participacion_inicializada_en=v_fecha,participacion_inicializada_por=p_actor_id WHERE id=v_id;
        END IF;
      END IF;
    END LOOP;
  EXCEPTION WHEN SQLSTATE 'PZ001' THEN
    GET STACKED DIAGNOSTICS v_detalle=PG_EXCEPTION_DETAIL;
    v_error:=v_detalle::jsonb; v_http:=(v_error->>'http_status')::integer;
    v_resultado:=NULL; v_plan:='[]'; v_anterior:=NULL; v_nuevo:=NULL; v_fecha:=clock_timestamp();
    INSERT INTO public.participacion_comando(actor_id,operacion,comando_id,huella,estado,error,http_terminal,creado_en,finalizado_en)
    VALUES(p_actor_id,p_operacion,p_comando_id,v_huella,'RECHAZADO',v_error->'error',v_http,v_fecha,v_fecha)
    RETURNING * INTO v_comando;
  END;
  RETURN public.pa_c_recibo(v_comando);
END $$;
-- Solo esta señal propia se convierte en rechazo durable; timeout/deadlock y
-- errores SQL inesperados atraviesan el wrapper y revierten toda la invocación.
CREATE OR REPLACE FUNCTION public.pa_c_rechazar(p_http INTEGER,p_codigo TEXT,p_mensaje TEXT)
RETURNS VOID LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public AS $$
BEGIN
  RAISE EXCEPTION USING ERRCODE='PZ001',MESSAGE='PA_RECHAZO_NEGOCIO',
    DETAIL=jsonb_build_object('http_status',p_http,'error',public.pa_c_error(p_codigo,p_mensaje))::text;
END $$;

-- Recuperación rápida: verifica identidad/actividad, pero nunca autoridad actual
-- para repetir un terminal. Si no hay fila no adquiere cuentas fuera de orden.
CREATE OR REPLACE FUNCTION public.pa_c_replay(
  p_actor_id BIGINT,p_auth_id TEXT,p_operacion TEXT,p_comando_id UUID,p_huella BYTEA
) RETURNS JSONB LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public AS $$
DECLARE v public.participacion_comando%ROWTYPE; v_activo BOOLEAN;
BEGIN
  SELECT * INTO v FROM public.participacion_comando
    WHERE actor_id=p_actor_id AND operacion=p_operacion AND comando_id=p_comando_id;
  IF NOT FOUND THEN RETURN NULL; END IF;
  SELECT activo INTO v_activo FROM public.usuario WHERE id=p_actor_id AND auth_id=p_auth_id FOR SHARE;
  IF NOT FOUND THEN RETURN public.pa_c_fuera(401,'SESION_INVALIDA','La sesión no es válida.',p_comando_id,'RECUPERAR_SESION'); END IF;
  IF NOT v_activo THEN RETURN public.pa_c_fuera(403,'CUENTA_INACTIVA','La cuenta no está activa.',p_comando_id); END IF;
  IF v.huella IS DISTINCT FROM p_huella THEN
    RETURN public.pa_c_fuera(409,'COMANDO_REUTILIZADO','La clave ya corresponde a otro contenido.',p_comando_id,'MISMA_CLAVE');
  END IF;
  RETURN public.pa_c_recibo(v);
END $$;

CREATE OR REPLACE FUNCTION public.pa_comando_recuperar(
  p_actor_id BIGINT,p_auth_id TEXT,p_operacion TEXT,p_comando_id UUID
) RETURNS JSONB LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public AS $$
DECLARE v public.participacion_comando%ROWTYPE; v_activo BOOLEAN;
BEGIN
  PERFORM set_config('lock_timeout','5s',true);
  IF p_operacion IS NULL OR p_operacion NOT IN ('REGISTRAR_PLANTACION_INICIAL',
    'OTORGAR_PLANTADOR','RETIRAR_PLANTADOR','DESIGNAR_ADMINISTRADOR',
    'CAMBIAR_ADMINISTRADOR_A_PLANTADOR','RETIRAR_ADMINISTRADOR','REEMPLAZAR_ADMINISTRADOR',
    'CAMBIAR_ROL_GLOBAL','INACTIVAR_CUENTA') OR p_comando_id IS NULL
    OR p_comando_id::text !~ '^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' THEN
    RETURN public.pa_c_fuera(422,'ENTRADA_INVALIDA','La entrada no es válida.',p_comando_id);
  END IF;
  SELECT activo INTO v_activo FROM public.usuario WHERE id=p_actor_id AND auth_id=p_auth_id FOR SHARE;
  IF NOT FOUND THEN RETURN public.pa_c_fuera(401,'SESION_INVALIDA','La sesión no es válida.',p_comando_id,'RECUPERAR_SESION'); END IF;
  IF NOT v_activo THEN RETURN public.pa_c_fuera(403,'CUENTA_INACTIVA','La cuenta no está activa.',p_comando_id); END IF;
  SELECT * INTO v FROM public.participacion_comando
    WHERE actor_id=p_actor_id AND operacion=p_operacion AND comando_id=p_comando_id;
  IF NOT FOUND THEN
    RETURN public.pa_c_fuera(404,'COMANDO_NO_CONFIRMADO','No hay un resultado confirmado para esta clave.',p_comando_id,'MISMA_CLAVE');
  END IF;
  IF v.estado='PREPARADO' THEN
    RETURN jsonb_build_object('http_status',202,'body',jsonb_build_object(
      'comando_id',p_comando_id,'operacion',p_operacion,'estado','SIN_RESULTADO',
      'resultado',NULL,'error',NULL,'finalizado_en',NULL));
  END IF;
  RETURN public.pa_c_recibo(v,true);
END $$;

CREATE OR REPLACE FUNCTION public.pa_autoridad_leer(p_actor_id BIGINT,p_auth_id TEXT,p_usuario_id BIGINT)
RETURNS JSONB LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public AS $$
DECLARE v_actor public.usuario%ROWTYPE; v_destino public.usuario%ROWTYPE; v_id BIGINT;
BEGIN
  PERFORM set_config('lock_timeout','5s',true);
  FOR v_id IN SELECT DISTINCT n FROM unnest(ARRAY[p_actor_id,p_usuario_id]) n ORDER BY n LOOP
    PERFORM 1 FROM public.usuario WHERE id=v_id FOR SHARE;
  END LOOP;
  SELECT * INTO v_actor FROM public.usuario WHERE id=p_actor_id AND auth_id=p_auth_id;
  IF NOT FOUND THEN RETURN public.pa_c_fuera(401,'SESION_INVALIDA','La sesión no es válida.',NULL,'RECUPERAR_SESION'); END IF;
  IF NOT v_actor.activo THEN RETURN public.pa_c_fuera(403,'CUENTA_INACTIVA','La cuenta no está activa.',NULL); END IF;
  IF v_actor.rol::text<>'ADMIN' THEN RETURN public.pa_c_fuera(403,'CAPACIDAD_INSUFICIENTE','No dispone de esta capacidad.',NULL); END IF;
  SELECT * INTO v_destino FROM public.usuario WHERE id=p_usuario_id;
  IF NOT FOUND THEN RETURN public.pa_c_fuera(404,'RECURSO_NO_VISIBLE','El recurso no está disponible.',NULL); END IF;
  RETURN jsonb_build_object('http_status',200,'body',jsonb_build_object('data',jsonb_build_object(
    'usuario_id',v_destino.id::text,'nombre',coalesce(nullif(btrim(v_destino.nombre),''),btrim(v_destino.username)),
    'rol_global',v_destino.rol::text,'activo',v_destino.activo,'revision_autoridad',v_destino.revision_autoridad::text),
    'observado_en',to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US"Z"')));
END $$;

-- Helper interno de efectos; el wrapper ya posee cuentas, ámbito y clave.
CREATE OR REPLACE FUNCTION public.pa_c_permiso_aplicar(
  p_actor_id BIGINT,p_comando_interno_id BIGINT,p_subcampania_id BIGINT,p_usuario_id BIGINT,
  p_permiso_nuevo TEXT,p_fecha TIMESTAMPTZ
) RETURNS BIGINT LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public AS $$
DECLARE v_vigencia BIGINT;
BEGIN
  INSERT INTO public.subcampania_permiso_revision(subcampania_id,usuario_id,revision,actualizado_en,actualizado_por)
  VALUES(p_subcampania_id,p_usuario_id,1,p_fecha,p_actor_id)
  ON CONFLICT(subcampania_id,usuario_id) DO UPDATE SET revision=subcampania_permiso_revision.revision+1,
    actualizado_en=p_fecha,actualizado_por=p_actor_id;
  UPDATE public.subcampania_permiso SET revocado_en=p_fecha,revocado_por=p_actor_id,comando_retiro_id=p_comando_interno_id
    WHERE subcampania_id=p_subcampania_id AND usuario_id=p_usuario_id AND revocado_en IS NULL;
  IF p_permiso_nuevo IS NOT NULL THEN
    INSERT INTO public.subcampania_permiso(subcampania_id,usuario_id,rol_contextual,otorgado_en,otorgado_por,comando_otorgamiento_id)
    VALUES(p_subcampania_id,p_usuario_id,p_permiso_nuevo,p_fecha,p_actor_id,p_comando_interno_id) RETURNING id INTO v_vigencia;
  END IF;
  RETURN v_vigencia;
END $$;

CREATE OR REPLACE FUNCTION public.pa_autoridad_ejecutar(
  p_actor_id BIGINT,p_auth_id TEXT,p_operacion TEXT,p_comando_id UUID,
  p_payload JSONB,p_contenido_canonico TEXT
) RETURNS JSONB LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public AS $$
DECLARE
  v_actor public.usuario%ROWTYPE; v_destino public.usuario%ROWTYPE;
  v_comando public.participacion_comando%ROWTYPE; v_id BIGINT; v_destino_id BIGINT;
  v_payload JSONB; v_replay JSONB; v_resultado JSONB; v_detalle TEXT; v_error JSONB;
  v_huella BYTEA; v_fecha TIMESTAMPTZ; v_rol TEXT; v_activo BOOLEAN; v_cambio BOOLEAN; v_http INTEGER;
BEGIN
  PERFORM set_config('lock_timeout','5s',true);
  IF p_operacion IS NULL OR p_operacion NOT IN ('CAMBIAR_ROL_GLOBAL','INACTIVAR_CUENTA')
    OR p_comando_id IS NULL OR p_comando_id::text !~ '^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
    OR jsonb_typeof(p_payload) IS DISTINCT FROM 'object' THEN
    RETURN public.pa_c_fuera(422,'ENTRADA_INVALIDA','La entrada no es válida.',p_comando_id);
  END IF;
  IF (p_payload-CASE WHEN p_operacion='CAMBIAR_ROL_GLOBAL' THEN ARRAY['usuario_destino_id','rol_global','revision_esperada','motivo']
    ELSE ARRAY['usuario_destino_id','revision_esperada','motivo'] END)<>'{}'::jsonb THEN
    RETURN public.pa_c_fuera(422,'CAMPO_NO_PERMITIDO','Hay campos no permitidos.',p_comando_id);
  END IF;
  IF NOT public.pa_c_decimal(p_payload->'usuario_destino_id') OR NOT public.pa_c_decimal(p_payload->'revision_esperada',true)
    OR jsonb_typeof(p_payload->'motivo') IS DISTINCT FROM 'string'
    OR char_length(normalize(btrim(p_payload->>'motivo'),NFC)) NOT BETWEEN 3 AND 1000
    OR (p_operacion='CAMBIAR_ROL_GLOBAL' AND COALESCE(p_payload->>'rol_global','') NOT IN ('ADMIN','GENERAL','VALIDADOR','VOLUNTARIO')) THEN
    RETURN public.pa_c_fuera(422,'ENTRADA_INVALIDA','La entrada no es válida.',p_comando_id);
  END IF;
  v_payload:=p_payload||jsonb_build_object('motivo',normalize(btrim(p_payload->>'motivo'),NFC));
  IF NOT public.pa_c_canon_coincide(p_contenido_canonico,v_payload) THEN
    RETURN public.pa_c_fuera(422,'ENTRADA_INVALIDA','El contenido canónico no corresponde a la intención.',p_comando_id);
  END IF;
  v_huella:=sha256(convert_to('PA-COMANDO/1'||chr(10)||p_operacion||chr(10)||p_contenido_canonico,'UTF8'));
  v_replay:=public.pa_c_replay(p_actor_id,p_auth_id,p_operacion,p_comando_id,v_huella);
  IF v_replay IS NOT NULL THEN RETURN v_replay; END IF;
  v_destino_id:=(v_payload->>'usuario_destino_id')::bigint;
  -- Mutex global -> cuentas ASC; el destino recibe UPDATE desde el inicio.
  PERFORM pg_advisory_xact_lock(hashtextextended('pa:autoridad_global:v1',0));
  FOR v_id IN SELECT DISTINCT n FROM unnest(ARRAY[p_actor_id,v_destino_id]) n ORDER BY n LOOP
    IF v_id=v_destino_id THEN PERFORM 1 FROM public.usuario WHERE id=v_id FOR UPDATE;
    ELSE PERFORM 1 FROM public.usuario WHERE id=v_id FOR SHARE; END IF;
  END LOOP;
  SELECT * INTO v_actor FROM public.usuario WHERE id=p_actor_id AND auth_id=p_auth_id;
  IF NOT FOUND THEN RETURN public.pa_c_fuera(401,'SESION_INVALIDA','La sesión no es válida.',p_comando_id,'RECUPERAR_SESION'); END IF;
  IF NOT v_actor.activo THEN RETURN public.pa_c_fuera(403,'CUENTA_INACTIVA','La cuenta no está activa.',p_comando_id); END IF;
  -- UPDATE del destino impide añadirle otra administración concurrente antes
  -- de descubrir TODOS sus ámbitos. Ninguna cuenta se bloquea después de éstos.
  IF p_operacion='INACTIVAR_CUENTA' THEN
    FOR v_id IN SELECT DISTINCT subcampania_id FROM public.subcampania_permiso
      WHERE usuario_id=v_destino_id AND rol_contextual='ADMINISTRADOR_SUBCAMPANIA' AND revocado_en IS NULL ORDER BY subcampania_id LOOP
      PERFORM 1 FROM public.subcampania WHERE id=v_id FOR UPDATE;
    END LOOP;
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('pa:comando:'||p_actor_id||':'||p_operacion||':'||p_comando_id,0));
  SELECT * INTO v_comando FROM public.participacion_comando
    WHERE actor_id=p_actor_id AND operacion=p_operacion AND comando_id=p_comando_id FOR UPDATE;
  IF FOUND THEN
    IF v_comando.huella IS DISTINCT FROM v_huella THEN
      RETURN public.pa_c_fuera(409,'COMANDO_REUTILIZADO','La clave ya corresponde a otro contenido.',p_comando_id,'MISMA_CLAVE');
    END IF;
    RETURN public.pa_c_recibo(v_comando);
  END IF;
  BEGIN
    IF v_actor.rol::text<>'ADMIN' THEN
      PERFORM public.pa_c_rechazar(403,'CAPACIDAD_INSUFICIENTE','No dispone de esta capacidad.');
    END IF;
    SELECT * INTO v_destino FROM public.usuario WHERE id=v_destino_id;
    IF NOT FOUND THEN PERFORM public.pa_c_rechazar(404,'RECURSO_NO_VISIBLE','El recurso no está disponible.'); END IF;
    IF v_destino.revision_autoridad<>(v_payload->>'revision_esperada')::bigint THEN
      PERFORM public.pa_c_rechazar(409,'REVISION_OBSOLETA','La revisión cambió; revise la cuenta.');
    END IF;
    IF p_operacion='CAMBIAR_ROL_GLOBAL' AND NOT v_destino.activo THEN
      PERFORM public.pa_c_rechazar(409,'DESTINO_INACTIVO','La cuenta destino no está activa.');
    END IF;
    v_rol:=CASE WHEN p_operacion='CAMBIAR_ROL_GLOBAL' THEN v_payload->>'rol_global' ELSE v_destino.rol::text END;
    v_activo:=CASE WHEN p_operacion='INACTIVAR_CUENTA' THEN false ELSE v_destino.activo END;
    IF v_destino.rol::text='ADMIN' AND v_destino.activo AND (v_rol<>'ADMIN' OR NOT v_activo)
      AND NOT EXISTS(SELECT 1 FROM public.usuario WHERE id<>v_destino_id AND rol::text='ADMIN' AND activo) THEN
      PERFORM public.pa_c_rechazar(409,'ULTIMO_ADMIN_GLOBAL','Debe permanecer un administrador global activo.');
    END IF;
    IF p_operacion='INACTIVAR_CUENTA' AND EXISTS(
      SELECT 1 FROM public.subcampania_permiso propio JOIN public.subcampania s ON s.id=propio.subcampania_id
      WHERE propio.usuario_id=v_destino_id AND propio.rol_contextual='ADMINISTRADOR_SUBCAMPANIA'
        AND propio.revocado_en IS NULL AND s.participacion_inicializada_en IS NOT NULL
        AND NOT EXISTS(SELECT 1 FROM public.subcampania_permiso otro JOIN public.usuario u ON u.id=otro.usuario_id
          WHERE otro.subcampania_id=s.id AND otro.usuario_id<>v_destino_id AND otro.rol_contextual='ADMINISTRADOR_SUBCAMPANIA'
            AND otro.revocado_en IS NULL AND u.activo)) THEN
      PERFORM public.pa_c_rechazar(409,'ULTIMO_ADMINISTRADOR_CONTEXTUAL','Debe permanecer un administrador contextual activo en cada ámbito.');
    END IF;
    v_cambio:=v_rol<>v_destino.rol::text OR v_activo<>v_destino.activo;
    IF v_cambio AND v_destino.revision_autoridad=9223372036854775807 THEN
      PERFORM public.pa_c_rechazar(409,'REVISION_OBSOLETA','La revisión no admite nuevos cambios.');
    END IF;
    v_resultado:=CASE WHEN p_operacion='CAMBIAR_ROL_GLOBAL' THEN jsonb_build_object(
      'tipo','ROL_GLOBAL','usuario_id',v_destino_id::text,'rol_anterior',v_destino.rol::text,'rol_nuevo',v_rol)
      ELSE jsonb_build_object('tipo','CUENTA_INACTIVADA','usuario_id',v_destino_id::text,'activo',false) END
      ||jsonb_build_object('revision_anterior',v_destino.revision_autoridad::text,
        'revision_nueva',(v_destino.revision_autoridad+CASE WHEN v_cambio THEN 1 ELSE 0 END)::text,
        'cambio',CASE WHEN v_cambio THEN 'CAMBIO_APLICADO' ELSE 'SIN_CAMBIOS' END);
    v_fecha:=clock_timestamp();
    INSERT INTO public.participacion_comando(actor_id,operacion,comando_id,huella,estado,resultado,http_terminal,creado_en,finalizado_en)
    VALUES(p_actor_id,p_operacion,p_comando_id,v_huella,'CONFIRMADO',v_resultado,200,v_fecha,v_fecha)
    ON CONFLICT(actor_id,operacion,comando_id) DO NOTHING RETURNING * INTO v_comando;
    IF NOT FOUND THEN
      SELECT * INTO STRICT v_comando FROM public.participacion_comando
        WHERE actor_id=p_actor_id AND operacion=p_operacion AND comando_id=p_comando_id FOR UPDATE;
      IF v_comando.huella IS DISTINCT FROM v_huella THEN
        RETURN public.pa_c_fuera(409,'COMANDO_REUTILIZADO','La clave ya corresponde a otro contenido.',p_comando_id,'MISMA_CLAVE');
      END IF;
      RETURN public.pa_c_recibo(v_comando);
    END IF;
    IF v_cambio THEN
      UPDATE public.usuario SET rol=v_rol::public.rol_usuario,activo=v_activo,revision_autoridad=revision_autoridad+1 WHERE id=v_destino_id;
      INSERT INTO public.usuario_autoridad_historial(comando_id,usuario_id,actor_id,evento,
        rol_anterior,rol_nuevo,activo_anterior,activo_nuevo,revision_anterior,revision_nueva,motivo,creado_en)
      VALUES(v_comando.id,v_destino_id,p_actor_id,CASE WHEN p_operacion='CAMBIAR_ROL_GLOBAL' THEN 'ROL_CAMBIADO' ELSE 'CUENTA_INACTIVADA' END,
        v_destino.rol,v_rol::public.rol_usuario,v_destino.activo,v_activo,v_destino.revision_autoridad,v_destino.revision_autoridad+1,
        v_payload->>'motivo',v_fecha);
    END IF;
  EXCEPTION WHEN SQLSTATE 'PZ001' THEN
    GET STACKED DIAGNOSTICS v_detalle=PG_EXCEPTION_DETAIL;
    v_error:=v_detalle::jsonb; v_http:=(v_error->>'http_status')::integer;
    v_resultado:=NULL; v_fecha:=clock_timestamp();
    INSERT INTO public.participacion_comando(actor_id,operacion,comando_id,huella,estado,error,http_terminal,creado_en,finalizado_en)
    VALUES(p_actor_id,p_operacion,p_comando_id,v_huella,'RECHAZADO',v_error->'error',v_http,v_fecha,v_fecha)
    RETURNING * INTO v_comando;
  END;
  RETURN public.pa_c_recibo(v_comando);
END $$;

-- Frontera privada: todas las sobrecargas; helpers solo en service_role para
-- las llamadas SECURITY INVOKER. RLS no sustituye la autoridad dentro de RPC.
DO $$ DECLARE v_funcion RECORD; v_columna RECORD; v_secuencia TEXT; v_rol TEXT; BEGIN
  REVOKE ALL ON public.usuario_autoridad_historial FROM PUBLIC,anon,authenticated,service_role;
  FOR v_columna IN SELECT attname FROM pg_attribute WHERE attrelid='public.usuario_autoridad_historial'::regclass
    AND attnum>0 AND NOT attisdropped LOOP
    EXECUTE format('REVOKE ALL (%I) ON public.usuario_autoridad_historial FROM PUBLIC,anon,authenticated,service_role',v_columna.attname);
  END LOOP;
  GRANT SELECT,INSERT ON public.usuario_autoridad_historial TO service_role;
  v_secuencia:=pg_get_serial_sequence('public.usuario_autoridad_historial','id');
  EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC,anon,authenticated,service_role',v_secuencia);
  EXECUTE format('GRANT USAGE ON SEQUENCE %s TO service_role',v_secuencia);
  FOR v_funcion IN SELECT p.oid::regprocedure AS firma FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
    WHERE n.nspname='public' AND (left(p.proname,5)='pa_c_' OR p.proname IN (
      'pa_acceso_ejecutar','pa_autoridad_ejecutar','pa_autoridad_leer','pa_comando_recuperar')) LOOP
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC,anon,authenticated,service_role',v_funcion.firma);
  END LOOP;
  GRANT EXECUTE ON FUNCTION public.pa_acceso_ejecutar(BIGINT,TEXT,TEXT,UUID,JSONB,TEXT),
    public.pa_autoridad_ejecutar(BIGINT,TEXT,TEXT,UUID,JSONB,TEXT),public.pa_autoridad_leer(BIGINT,TEXT,BIGINT),
    public.pa_comando_recuperar(BIGINT,TEXT,TEXT,UUID),public.pa_c_error(TEXT,TEXT,TEXT,JSONB,JSONB),
    public.pa_c_fuera(INTEGER,TEXT,TEXT,UUID,TEXT),public.pa_c_recibo(public.participacion_comando,BOOLEAN),
    public.pa_c_decimal(JSONB,BOOLEAN),public.pa_c_canon_coincide(TEXT,JSONB),public.pa_c_rechazar(INTEGER,TEXT,TEXT),
