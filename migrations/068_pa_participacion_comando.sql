-- Orden: 068 antes de las FKs de permisos/historial y del bootstrap de INT02-B.
-- No instala motor, despacho, recuperación HTTP ni canonicalizador de INT03-A.
-- Los nombres de acceso/autoridad se reservan; esta tabla no habilita operaciones.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

DO $$ DECLARE v_tabla TEXT; BEGIN
  FOREACH v_tabla IN ARRAY ARRAY['usuario','subcampania','registro_plantacion'] LOOP
    IF to_regclass(format('public.%I',v_tabla)) IS NULL THEN
      RAISE EXCEPTION 'PA_COMANDO_FALTA_DEPENDENCIA: %',v_tabla;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_attribute
      WHERE attrelid=to_regclass(format('public.%I',v_tabla)) AND attname='id'
        AND atttypid='bigint'::regtype AND attnotnull AND NOT attisdropped) THEN
      RAISE EXCEPTION 'PA_COMANDO_ID_INCOMPATIBLE: %',v_tabla;
    END IF;
  END LOOP;
END $$;

CREATE TABLE IF NOT EXISTS public.participacion_comando (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT NOT NULL,
  operacion TEXT NOT NULL,
  comando_id UUID NOT NULL,
  version_contrato SMALLINT NOT NULL DEFAULT 1,
  version_huella SMALLINT NOT NULL DEFAULT 1,
  huella BYTEA,
  estado TEXT NOT NULL,
  subcampania_preparacion_id BIGINT,
  registro_plantacion_id BIGINT,
  resultado JSONB,
  error JSONB,
  http_terminal SMALLINT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  finalizado_en TIMESTAMPTZ,

  CONSTRAINT participacion_comando_actor_fk FOREIGN KEY (actor_id)
    REFERENCES public.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT participacion_comando_preparacion_fk FOREIGN KEY (subcampania_preparacion_id)
    REFERENCES public.subcampania(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT participacion_comando_registro_fk FOREIGN KEY (registro_plantacion_id)
    REFERENCES public.registro_plantacion(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT participacion_comando_identidad_uq UNIQUE (actor_id,operacion,comando_id),
  CONSTRAINT participacion_comando_id_actor_uq UNIQUE (id,actor_id),
  CONSTRAINT participacion_comando_version_ck CHECK (version_contrato>0 AND version_huella>0),
  CONSTRAINT participacion_comando_operacion_ck CHECK (operacion IN (
    'REGISTRAR_PLANTACION_INICIAL',
    'OTORGAR_PLANTADOR','RETIRAR_PLANTADOR','DESIGNAR_ADMINISTRADOR',
    'CAMBIAR_ADMINISTRADOR_A_PLANTADOR','RETIRAR_ADMINISTRADOR','REEMPLAZAR_ADMINISTRADOR',
    'CAMBIAR_ROL_GLOBAL','INACTIVAR_CUENTA',
    'INICIALIZAR_PARTICIPACION_LEGADA'
  )),
  CONSTRAINT participacion_comando_estado_ck CHECK (estado IN ('PREPARADO','CONFIRMADO','RECHAZADO')),
  CONSTRAINT participacion_comando_huella_ck CHECK (huella IS NULL OR octet_length(huella)=32),
  CONSTRAINT participacion_comando_objetos_ck CHECK (
    (resultado IS NULL OR jsonb_typeof(resultado)='object') AND
    (error IS NULL OR jsonb_typeof(error)='object')
  ),
  CONSTRAINT participacion_comando_fechas_ck CHECK (finalizado_en IS NULL OR finalizado_en>=creado_en),
  CONSTRAINT participacion_comando_ciclo_ck CHECK (
    (estado='PREPARADO' AND operacion='REGISTRAR_PLANTACION_INICIAL'
      AND subcampania_preparacion_id IS NOT NULL AND huella IS NULL
      AND registro_plantacion_id IS NULL AND resultado IS NULL AND error IS NULL
      AND http_terminal IS NULL AND finalizado_en IS NULL)
    OR
    (estado='CONFIRMADO' AND huella IS NOT NULL AND resultado IS NOT NULL
      AND error IS NULL AND http_terminal IS NOT NULL AND http_terminal=200
      AND finalizado_en IS NOT NULL)
    OR
    (estado='RECHAZADO' AND resultado IS NULL AND error IS NOT NULL
      AND registro_plantacion_id IS NULL AND http_terminal IS NOT NULL
      AND http_terminal IN (403,404,409,422,503) AND finalizado_en IS NOT NULL
      AND (huella IS NOT NULL OR COALESCE(
        operacion='REGISTRAR_PLANTACION_INICIAL' AND subcampania_preparacion_id IS NOT NULL
        AND http_terminal=409 AND error->>'codigo'='PREPARACION_CANCELADA',false)))
  ),
  CONSTRAINT participacion_comando_scope_ck CHECK (
    operacion='REGISTRAR_PLANTACION_INICIAL' OR subcampania_preparacion_id IS NULL
  ),
  CONSTRAINT participacion_comando_registro_resultado_ck CHECK (
    CASE WHEN estado='CONFIRMADO' AND operacion='REGISTRAR_PLANTACION_INICIAL' THEN
      registro_plantacion_id IS NOT NULL AND subcampania_preparacion_id IS NOT NULL AND COALESCE(
        jsonb_typeof(resultado->'registro_plantacion_id')='string'
        AND resultado->>'registro_plantacion_id'=registro_plantacion_id::TEXT
        AND jsonb_typeof(resultado->'subcampania_id')='string'
        AND resultado->>'subcampania_id'=subcampania_preparacion_id::TEXT
        AND resultado->>'tipo'='PLANTACION_INICIAL',false)
    ELSE registro_plantacion_id IS NULL END
  ),
  CONSTRAINT participacion_comando_resultado_tipo_ck CHECK (
    estado<>'CONFIRMADO' OR COALESCE(resultado->>'tipo'=CASE
      WHEN operacion='REGISTRAR_PLANTACION_INICIAL' THEN 'PLANTACION_INICIAL'
      WHEN operacion='CAMBIAR_ROL_GLOBAL' THEN 'ROL_GLOBAL'
      WHEN operacion='INACTIVAR_CUENTA' THEN 'CUENTA_INACTIVADA'
      WHEN operacion='INICIALIZAR_PARTICIPACION_LEGADA' THEN 'INICIALIZACION_PARTICIPACION_LEGADA'
      ELSE 'ACCESO' END,false)
  ),
  CONSTRAINT participacion_comando_error_ck CHECK (
    error IS NULL OR COALESCE(
      jsonb_typeof(error->'codigo')='string' AND btrim(error->>'codigo')<>''
      AND jsonb_typeof(error->'mensaje')='string' AND btrim(error->>'mensaje')<>''
      AND jsonb_typeof(error->'campos')='array' AND jsonb_typeof(error->'ambitos')='array'
      AND error->>'reintento' IN ('MISMA_CLAVE','NUEVA_CONFIRMACION','RECUPERAR_SESION','NO_APLICA'),false)
  )
);

-- Una estructura preexistente incompatible no se acepta por IF NOT EXISTS.
-- Este cotejo local no sustituye el inventario del catálogo del entorno destino.
DO $$ DECLARE v RECORD; BEGIN
  FOR v IN SELECT * FROM (VALUES
    ('id','bigint',true),('actor_id','bigint',true),('operacion','text',true),
    ('comando_id','uuid',true),('version_contrato','smallint',true),('version_huella','smallint',true),
    ('huella','bytea',false),('estado','text',true),('subcampania_preparacion_id','bigint',false),
    ('registro_plantacion_id','bigint',false),('resultado','jsonb',false),('error','jsonb',false),
    ('http_terminal','smallint',false),('creado_en','timestamp with time zone',true),
    ('finalizado_en','timestamp with time zone',false)
  ) AS esperado(columna,tipo,obligatoria) LOOP
    IF NOT EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid='public.participacion_comando'::regclass
      AND attname=v.columna AND atttypid=v.tipo::regtype AND attnotnull=v.obligatoria AND NOT attisdropped) THEN
      RAISE EXCEPTION 'PA_COMANDO_COLUMNA_INCOMPATIBLE: %',v.columna;
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM unnest(ARRAY[
    'participacion_comando_pkey','participacion_comando_actor_fk','participacion_comando_preparacion_fk',
    'participacion_comando_registro_fk','participacion_comando_identidad_uq','participacion_comando_id_actor_uq',
    'participacion_comando_version_ck','participacion_comando_operacion_ck','participacion_comando_estado_ck',
    'participacion_comando_huella_ck','participacion_comando_objetos_ck','participacion_comando_fechas_ck',
    'participacion_comando_ciclo_ck','participacion_comando_scope_ck','participacion_comando_registro_resultado_ck',
    'participacion_comando_resultado_tipo_ck','participacion_comando_error_ck'
  ]) AS esperado(nombre) WHERE NOT EXISTS (SELECT 1 FROM pg_constraint
    WHERE conrelid='public.participacion_comando'::regclass AND conname=esperado.nombre AND convalidated)) THEN
    RAISE EXCEPTION 'PA_COMANDO_RESTRICCIONES_INCOMPATIBLES';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.participacion_comando'::regclass
    AND contype='f' AND (confdeltype<>'r' OR confupdtype<>'r')) THEN
    RAISE EXCEPTION 'PA_COMANDO_FK_NO_RESTRICT';
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS participacion_comando_actor_fecha_idx
  ON public.participacion_comando(actor_id,creado_en,id);
CREATE INDEX IF NOT EXISTS participacion_comando_preparado_fecha_idx
  ON public.participacion_comando(creado_en) WHERE estado='PREPARADO';
CREATE UNIQUE INDEX IF NOT EXISTS participacion_comando_inicial_registro_uq
  ON public.participacion_comando(registro_plantacion_id)
  WHERE operacion='REGISTRAR_PLANTACION_INICIAL' AND estado='CONFIRMADO';

COMMENT ON TABLE public.participacion_comando IS
