  'SHA-256 del servidor; canonicalización/versionado de dominio se implementa en INT03-A. Bootstrap usa manifest revisado, no payload HTTP.';

-- Defensa de identidad/preparación y tombstone. El motor futuro puede terminar una
-- preparación una vez; no puede reabrir/editar un terminal ni reciclar su clave.
CREATE OR REPLACE FUNCTION public.pa_participacion_comando_proteger()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public AS $$
BEGIN
  IF TG_OP IN ('DELETE','TRUNCATE') THEN
    RAISE EXCEPTION 'PA_COMANDO_CONSERVACION_OBLIGATORIA' USING ERRCODE='55000';
  END IF;
  IF OLD.estado IN ('CONFIRMADO','RECHAZADO') THEN
    RAISE EXCEPTION 'PA_COMANDO_TERMINAL_INMUTABLE' USING ERRCODE='55000';
  END IF;
  IF ROW(NEW.id,NEW.actor_id,NEW.operacion,NEW.comando_id,NEW.version_contrato,
      NEW.version_huella,NEW.subcampania_preparacion_id,NEW.creado_en)
    IS DISTINCT FROM ROW(OLD.id,OLD.actor_id,OLD.operacion,OLD.comando_id,OLD.version_contrato,
      OLD.version_huella,OLD.subcampania_preparacion_id,OLD.creado_en) THEN
    RAISE EXCEPTION 'PA_COMANDO_IDENTIDAD_INMUTABLE' USING ERRCODE='55000';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS participacion_comando_proteger_fila_trg ON public.participacion_comando;
CREATE TRIGGER participacion_comando_proteger_fila_trg
  BEFORE UPDATE OR DELETE ON public.participacion_comando
  FOR EACH ROW EXECUTE FUNCTION public.pa_participacion_comando_proteger();
DROP TRIGGER IF EXISTS participacion_comando_proteger_truncate_trg ON public.participacion_comando;
CREATE TRIGGER participacion_comando_proteger_truncate_trg
  BEFORE TRUNCATE ON public.participacion_comando
  FOR EACH STATEMENT EXECUTE FUNCTION public.pa_participacion_comando_proteger();

ALTER TABLE public.participacion_comando ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.participacion_comando FROM PUBLIC,anon,authenticated,service_role;
GRANT SELECT,INSERT,UPDATE ON TABLE public.participacion_comando TO service_role;
DO $$ DECLARE v_columnas TEXT; v_secuencia TEXT; v_funcion RECORD; v_rol TEXT; BEGIN
  SELECT string_agg(quote_ident(attname),', ' ORDER BY attnum) INTO v_columnas FROM pg_attribute
    WHERE attrelid='public.participacion_comando'::regclass AND attnum>0 AND NOT attisdropped;
  EXECUTE format('REVOKE SELECT (%s), INSERT (%s), UPDATE (%s), REFERENCES (%s) ON public.participacion_comando FROM PUBLIC,anon,authenticated',
    v_columnas,v_columnas,v_columnas,v_columnas);
  v_secuencia:=pg_get_serial_sequence('public.participacion_comando','id');
  IF v_secuencia IS NULL THEN RAISE EXCEPTION 'PA_COMANDO_IDENTIDAD_SIN_SECUENCIA'; END IF;
  EXECUTE format('REVOKE ALL PRIVILEGES ON SEQUENCE %s FROM PUBLIC,anon,authenticated,service_role',v_secuencia);
  EXECUTE format('GRANT USAGE ON SEQUENCE %s TO service_role',v_secuencia);
  -- Incluye sobrecargas; el helper de trigger no es un entrypoint de backend.
  FOR v_funcion IN SELECT p.oid::regprocedure AS firma FROM pg_proc p
    JOIN pg_namespace n ON n.oid=p.pronamespace
    WHERE n.nspname='public' AND p.prokind='f' AND p.proname='pa_participacion_comando_proteger' LOOP
    EXECUTE format('REVOKE EXECUTE ON FUNCTION %s FROM PUBLIC,anon,authenticated,service_role',v_funcion.firma);
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_policy WHERE polrelid='public.participacion_comando'::regclass
    AND (0::OID=ANY(polroles) OR EXISTS (SELECT 1 FROM pg_roles WHERE rolname IN ('anon','authenticated') AND oid=ANY(polroles)))) THEN
    RAISE EXCEPTION 'PA_COMANDO_POLITICA_PUBLICA_INCOMPATIBLE';
  END IF;
  FOREACH v_rol IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
      WHERE n.nspname='public' AND p.proname='pa_participacion_comando_proteger'
        AND has_function_privilege(v_rol,p.oid,'EXECUTE')) THEN
      RAISE EXCEPTION 'PA_COMANDO_HELPER_EXECUTE_HEREDADO: %',v_rol;
    END IF;
    IF has_any_column_privilege(v_rol,'public.participacion_comando','SELECT')
      OR has_any_column_privilege(v_rol,'public.participacion_comando','INSERT')
      OR has_any_column_privilege(v_rol,'public.participacion_comando','UPDATE')
      OR has_any_column_privilege(v_rol,'public.participacion_comando','REFERENCES')
      OR has_table_privilege(v_rol,'public.participacion_comando','DELETE')
      OR has_table_privilege(v_rol,'public.participacion_comando','TRUNCATE')
      OR has_table_privilege(v_rol,'public.participacion_comando','TRIGGER')
      OR has_sequence_privilege(v_rol,v_secuencia,'USAGE,SELECT,UPDATE') THEN
      RAISE EXCEPTION 'PA_COMANDO_PRIVILEGIO_PUBLICO_HEREDADO: %',v_rol;
    END IF;
  END LOOP;
  IF has_table_privilege('service_role','public.participacion_comando','DELETE')
    OR has_table_privilege('service_role','public.participacion_comando','TRUNCATE')
    OR has_sequence_privilege('service_role',v_secuencia,'UPDATE') THEN
    RAISE EXCEPTION 'PA_COMANDO_PRIVILEGIO_CONSERVACION_INCOMPATIBLE';
  END IF;
END $$;
