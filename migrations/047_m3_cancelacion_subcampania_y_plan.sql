-- =====================================================================
-- 4. RPC fn_subcampania_cancelar (RN-PLA-37)
-- =====================================================================

CREATE OR REPLACE FUNCTION public.fn_subcampania_cancelar(
  p_id BIGINT,
  p_actor_user_id BIGINT,
  p_motivo TEXT
)
RETURNS public.subcampania
LANGUAGE plpgsql
AS $$
DECLARE
  v_sub public.subcampania%ROWTYPE;
  v_asignaciones_liberadas INT;
BEGIN
  IF p_motivo IS NULL OR btrim(p_motivo) = '' THEN
    RAISE EXCEPTION 'El motivo de cancelacion es obligatorio.'
      USING ERRCODE = 'P0001';
  END IF;

  -- Lock pesimista de la subcampania para evitar carreras con plantacion.
  SELECT *
  INTO v_sub
  FROM public.subcampania
  WHERE id = p_id
    AND deleted_at IS NULL
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Subcampania % no encontrada.', p_id
      USING ERRCODE = 'P0002';
  END IF;

  IF v_sub.estado NOT IN ('BORRADOR', 'ACTIVA') THEN
    RAISE EXCEPTION
      'Solo se puede cancelar una subcampania en BORRADOR o ACTIVA (estado actual: %).',
      v_sub.estado
      USING ERRCODE = 'P0001';
  END IF;

  IF COALESCE(v_sub.total_plantado_inicial, 0) > 0 THEN
    RAISE EXCEPTION
      'La subcampania ya tiene plantaciones registradas (total_plantado_inicial = %). Usar cierre FINALIZADA_PARCIAL.',
      v_sub.total_plantado_inicial
      USING ERRCODE = 'P0001';
  END IF;

  -- Bloquear asignaciones activas antes de liberarlas (evita carreras
  -- con nuevas reservas / devoluciones).
  PERFORM 1
  FROM public.asignacion_vivero_subcampania
  WHERE subcampania_id = p_id
    AND estado = 'ACTIVA'
  FOR UPDATE;

  -- Devolucion logica de todas las asignaciones activas. El trigger
  -- asignacion_vivero_subcampania_estado_trg pasara cada fila a 'DEVUELTA'.
  UPDATE public.asignacion_vivero_subcampania
     SET cantidad_devuelta =
         cantidad_devuelta + saldo_asignado_disponible
   WHERE subcampania_id = p_id
     AND estado = 'ACTIVA'
     AND saldo_asignado_disponible > 0;

  GET DIAGNOSTICS v_asignaciones_liberadas = ROW_COUNT;

  -- Marcar subcampania como CANCELADA. Inactivacion, no borrado fisico:
  -- se conserva la fila con deleted_at/deleted_by para trazabilidad.
  UPDATE public.subcampania
     SET estado      = 'CANCELADA',
         deleted_at  = NOW(),
         deleted_by  = p_actor_user_id,
         updated_at  = NOW(),
         updated_by  = p_actor_user_id
   WHERE id = p_id
  RETURNING * INTO v_sub;

  -- Registrar evento en historial.
  INSERT INTO public.subcampania_historial (
    subcampania_id,
    tipo_historial,
    estado_origen,
    estado_destino,
    observaciones,
    metadata,
    actor_user_id
  )
  VALUES (
    p_id,
    'SUBCAMPANIA_CANCELADA',
    -- estado_origen: leemos el previo a este UPDATE — no vive en v_sub tras el RETURNING,
    -- asi que lo dejamos en NULL y guardamos el detalle en metadata.
    NULL,
    'CANCELADA',
    p_motivo,
    jsonb_build_object(
      'asignaciones_liberadas', v_asignaciones_liberadas,
      'motivo_devolucion', 'CIERRE_SUBCAMPANIA'
    ),
    p_actor_user_id
  );

  RETURN v_sub;
END;
$$;

COMMENT ON FUNCTION public.fn_subcampania_cancelar(BIGINT, BIGINT, TEXT) IS
  'Cancela una subcampania sin plantaciones (RN-PLA-37): setea estado=CANCELADA, libera asignaciones activas como devolucion logica (sin evento M2, ver RN-VIV-48) y registra SUBCAMPANIA_CANCELADA en historial. Atomico.';

-- =====================================================================
-- 5. RPC fn_vivero_reservar_stock_lote — guard por proposito
-- =====================================================================
-- Actualiza el guard de 045: rechaza siempre BORRADOR y CANCELADA.
-- PLANTACION_INICIAL solo con subcampania ACTIVA.
-- REPOSICION con ACTIVA, COMPLETADA o FINALIZADA_PARCIAL (RN-PLA-12).

CREATE OR REPLACE FUNCTION public.fn_vivero_reservar_stock_lote(
  p_lote_vivero_id BIGINT,
  p_subcampania_id BIGINT,
  p_cantidad_asignada INT,
  p_proposito public.proposito_asignacion,
  p_usuario_asignacion_id BIGINT
)
RETURNS public.asignacion_vivero_subcampania
LANGUAGE plpgsql
AS $$
DECLARE
  v_lote public.lote_vivero%ROWTYPE;
  v_subcampania_estado public.estado_subcampania;
  v_saldo_reservado INT;
  v_saldo_disponible INT;
  v_asignacion public.asignacion_vivero_subcampania%ROWTYPE;
BEGIN
  IF p_cantidad_asignada IS NULL OR p_cantidad_asignada <= 0 THEN
    RAISE EXCEPTION 'No se puede reservar una cantidad menor o igual a 0.';
  END IF;

  SELECT *
  INTO v_lote
  FROM public.lote_vivero
  WHERE id = p_lote_vivero_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Lote de vivero % no encontrado.', p_lote_vivero_id;
  END IF;

  IF v_lote.estado_lote IS DISTINCT FROM 'ACTIVO' THEN
    RAISE EXCEPTION
      'No se puede reservar desde un lote en estado %.',
      v_lote.estado_lote;
  END IF;

  IF v_lote.saldo_vivo_actual IS NULL OR v_lote.saldo_vivo_actual <= 0 THEN
    RAISE EXCEPTION 'El lote % no tiene saldo vivo disponible.', p_lote_vivero_id;
  END IF;

  SELECT estado
  INTO v_subcampania_estado
  FROM public.subcampania
  WHERE id = p_subcampania_id
    AND deleted_at IS NULL
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Subcampania % no encontrada.', p_subcampania_id;
  END IF;

  -- Nunca se acepta reserva contra BORRADOR ni CANCELADA (RN-VIV-11 / RF-PLA-04).
  IF v_subcampania_estado IN ('BORRADOR', 'CANCELADA') THEN
    RAISE EXCEPTION
      'No se puede reservar para una subcampania en estado %. Solo se admite tras activar y siempre que no este cancelada.',
      v_subcampania_estado;
  END IF;

  -- Guard por proposito (RN-PLA-12).
  IF p_proposito = 'PLANTACION_INICIAL' AND v_subcampania_estado <> 'ACTIVA' THEN
    RAISE EXCEPTION
      'PLANTACION_INICIAL solo se permite con la subcampania en ACTIVA (estado actual: %).',
      v_subcampania_estado;
  END IF;

  IF p_proposito = 'REPOSICION'
     AND v_subcampania_estado NOT IN ('ACTIVA', 'COMPLETADA', 'FINALIZADA_PARCIAL') THEN
    RAISE EXCEPTION
      'REPOSICION solo se permite con la subcampania en ACTIVA, COMPLETADA o FINALIZADA_PARCIAL (estado actual: %).',
      v_subcampania_estado;
  END IF;

  PERFORM 1
  FROM public.asignacion_vivero_subcampania
  WHERE lote_vivero_id = p_lote_vivero_id
    AND estado = 'ACTIVA'
  FOR UPDATE;

  SELECT COALESCE(SUM(saldo_asignado_disponible), 0)::INT
  INTO v_saldo_reservado
  FROM public.asignacion_vivero_subcampania
  WHERE lote_vivero_id = p_lote_vivero_id
    AND estado = 'ACTIVA';

  v_saldo_disponible := v_lote.saldo_vivo_actual - v_saldo_reservado;

  IF p_cantidad_asignada > v_saldo_disponible THEN
    RAISE EXCEPTION
      'La cantidad solicitada (%) excede el saldo vivo disponible para asignacion del lote % (%).',
      p_cantidad_asignada,
      p_lote_vivero_id,
      v_saldo_disponible;
  END IF;

  INSERT INTO public.asignacion_vivero_subcampania (
    lote_vivero_id,
    subcampania_id,
    cantidad_asignada,
    proposito,
    usuario_asignacion_id
  )
  VALUES (
    p_lote_vivero_id,
    p_subcampania_id,
    p_cantidad_asignada,
    p_proposito,
    p_usuario_asignacion_id
  )
  RETURNING * INTO v_asignacion;

  RETURN v_asignacion;
END;
$$;

COMMENT ON FUNCTION public.fn_vivero_reservar_stock_lote(
  BIGINT,
  BIGINT,
  INT,
  public.proposito_asignacion,
  BIGINT
) IS
  'Reserva stock de un lote para una subcampania. Rechaza siempre BORRADOR y CANCELADA; PLANTACION_INICIAL requiere ACTIVA; REPOSICION admite ACTIVA/COMPLETADA/FINALIZADA_PARCIAL (RN-VIV-11, RN-PLA-12).';

