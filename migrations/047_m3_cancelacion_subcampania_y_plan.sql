-- =====================================================================
-- 2. Tabla subcampania_historial (append-only)
-- =====================================================================

CREATE TABLE IF NOT EXISTS public.subcampania_historial (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subcampania_id    BIGINT NOT NULL,
  tipo_historial    public.tipo_historial_subcampania NOT NULL,
  estado_origen     public.estado_subcampania,
  estado_destino    public.estado_subcampania,
  observaciones     TEXT,
  metadata          JSONB NOT NULL DEFAULT '{}'::jsonb,
  actor_user_id     BIGINT,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT subcampania_historial_subcampania_fk
    FOREIGN KEY (subcampania_id)
    REFERENCES public.subcampania (id)
    ON DELETE RESTRICT,

  CONSTRAINT subcampania_historial_actor_fk
    FOREIGN KEY (actor_user_id)
    REFERENCES public.usuario (id)
    ON DELETE SET NULL,

  CONSTRAINT subcampania_historial_metadata_object_chk
    CHECK (jsonb_typeof(metadata) = 'object')
);

CREATE INDEX IF NOT EXISTS subcampania_historial_subcampania_idx
  ON public.subcampania_historial (subcampania_id);

CREATE INDEX IF NOT EXISTS subcampania_historial_subcampania_created_at_idx
  ON public.subcampania_historial (subcampania_id, created_at);

CREATE INDEX IF NOT EXISTS subcampania_historial_tipo_idx
  ON public.subcampania_historial (tipo_historial);

CREATE INDEX IF NOT EXISTS subcampania_historial_actor_idx
  ON public.subcampania_historial (actor_user_id);

COMMENT ON TABLE public.subcampania_historial IS
  'Historial append-only del ciclo de vida de la subcampania (RN-PLA-06/37, docs §4.1).';

-- Append-only: bloquear UPDATE/DELETE/TRUNCATE.
CREATE OR REPLACE FUNCTION public.fn_subcampania_historial_prevent_mutation()
RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION
    'public.subcampania_historial es append-only: no se permite %, solo INSERT.',
    TG_OP;
END $$;

DROP TRIGGER IF EXISTS subcampania_historial_prevent_mutation_trg
  ON public.subcampania_historial;

CREATE TRIGGER subcampania_historial_prevent_mutation_trg
  BEFORE UPDATE OR DELETE OR TRUNCATE ON public.subcampania_historial
  FOR EACH STATEMENT
  EXECUTE FUNCTION public.fn_subcampania_historial_prevent_mutation();

