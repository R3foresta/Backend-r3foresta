-- PostGIS ni datos de personas reales; subcampania sólo sirve a los triggers037/050.
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN;
GRANT USAGE ON SCHEMA public TO anon,authenticated,service_role;

CREATE TYPE public.rol_usuario AS ENUM('ADMIN','GENERAL','VALIDADOR','PLANTADOR','VOLUNTARIO');
CREATE TYPE public.tipo_subcampania AS ENUM('REFORESTACION','ARBORIZACION','FORESTACION');
CREATE TABLE public.usuario (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_id text NOT NULL UNIQUE,
  nombre text NOT NULL,
  rol public.rol_usuario NOT NULL,
  activo boolean NOT NULL DEFAULT true
);
CREATE TABLE public.subcampania (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campania_id bigint NOT NULL,
  tipo public.tipo_subcampania NOT NULL,
  estado text NOT NULL DEFAULT 'BORRADOR',
  deleted_at timestamptz
);

