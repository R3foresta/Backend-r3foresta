-- SINTETICO_AISLADO. Antecedente mínimo relevante después de INT02-A/067.
-- No reconstruye 001–067 ni acredita PostGIS, Storage o el catálogo remoto.
-- Tipos/columnas relevantes corresponden a 029/030/047/062/064. Los campos
-- geométricos/logísticos que no usa INT02-B quedan fuera de esta fixture.
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN BYPASSRLS;
CREATE ROLE pa_int02b_public_probe NOLOGIN;
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role, pa_int02b_public_probe;

CREATE TYPE public.rol_usuario AS ENUM ('ADMIN','GENERAL','VALIDADOR','VOLUNTARIO');
CREATE TYPE public.estado_subcampania AS ENUM (
  'BORRADOR','ACTIVA','COMPLETADA','FINALIZADA_PARCIAL','PAUSADA','CANCELADA'
);
CREATE TYPE public.rol_en_subcampania AS ENUM ('COORDINADOR','OPERARIO');
CREATE TYPE public.tipo_historial_subcampania AS ENUM (
  'BORRADOR_CREADO','SUBCAMPANIA_ACTIVADA','SUBCAMPANIA_COMPLETADA',
  'SUBCAMPANIA_FINALIZADA_PARCIAL','SUBCAMPANIA_CANCELADA',
  'TRANSICION_A_MONITOREO_HISTORICO','EQUIPO_AMPLIADO','EQUIPO_REDUCIDO',
  'COORDINADOR_CAMBIADO','PLAN_REVISADO'
);
CREATE TABLE public.organizacion (
  id BIGINT PRIMARY KEY, nombre TEXT NOT NULL, activo BOOLEAN NOT NULL DEFAULT true
);
CREATE TABLE public.usuario (
  id BIGINT PRIMARY KEY,
  auth_id TEXT NOT NULL UNIQUE CHECK (btrim(auth_id)<>''),
  username TEXT, nombre TEXT, apellido TEXT, organizacion TEXT,
  rol public.rol_usuario NOT NULL DEFAULT 'VOLUNTARIO',
  activo BOOLEAN NOT NULL DEFAULT true,
  revision_autoridad BIGINT NOT NULL DEFAULT 0 CHECK(revision_autoridad>=0),
  organizacion_id BIGINT REFERENCES public.organizacion(id) ON DELETE RESTRICT,
  doc_identidad TEXT UNIQUE, wallet_address TEXT UNIQUE, contacto TEXT,
  foto_perfil_url TEXT,
  CHECK (organizacion_id IS NULL OR organizacion IS NULL)
);
CREATE TABLE public.subcampania (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campania_id BIGINT NOT NULL DEFAULT 1,
  nombre TEXT NOT NULL, estado public.estado_subcampania NOT NULL,
  codigo_trazabilidad TEXT NOT NULL UNIQUE,
  meta_total_arboles INT NOT NULL DEFAULT 100 CHECK(meta_total_arboles>0),
  total_plantado_inicial INT NOT NULL DEFAULT 0,
  total_repuesto INT NOT NULL DEFAULT 0,
  total_muerto_acumulado INT NOT NULL DEFAULT 0,
  saldo_vivo_actual INT GENERATED ALWAYS AS (
    total_plantado_inicial+total_repuesto-total_muerto_acumulado
  ) STORED,
  plan_revision BIGINT NOT NULL DEFAULT 0 CHECK(plan_revision>=0),
  fecha_cierre_operativo TIMESTAMPTZ, fecha_fin_mantenimiento DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT '2026-10-01T12:00:00Z',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT '2026-10-01T12:00:00Z',
  created_by BIGINT NOT NULL REFERENCES public.usuario(id),
  updated_by BIGINT NOT NULL REFERENCES public.usuario(id),
  deleted_at TIMESTAMPTZ, deleted_by BIGINT REFERENCES public.usuario(id)
);
CREATE TABLE public.subcampania_equipo (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subcampania_id BIGINT NOT NULL REFERENCES public.subcampania(id) ON DELETE CASCADE,
  usuario_id BIGINT NOT NULL REFERENCES public.usuario(id),
  rol public.rol_en_subcampania NOT NULL,
  agregado_at TIMESTAMPTZ NOT NULL DEFAULT '2026-10-01T12:00:00Z',
  agregado_by BIGINT NOT NULL REFERENCES public.usuario(id),
  UNIQUE(subcampania_id,usuario_id)
);
CREATE UNIQUE INDEX subcampania_equipo_un_coordinador_idx
  ON public.subcampania_equipo(subcampania_id) WHERE rol='COORDINADOR';
CREATE TABLE public.subcampania_historial (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subcampania_id BIGINT NOT NULL REFERENCES public.subcampania(id) ON DELETE RESTRICT,
  tipo_historial public.tipo_historial_subcampania NOT NULL,
  estado_origen public.estado_subcampania,
  estado_destino public.estado_subcampania,
  observaciones TEXT, metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  actor_user_id BIGINT REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT '2026-10-01T12:00:00Z',
  CHECK(jsonb_typeof(metadata)='object')
);
CREATE FUNCTION public.fn_subcampania_historial_prevent_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
  RAISE EXCEPTION 'public.subcampania_historial es append-only: no se permite %, solo INSERT.', TG_OP;
END $$;
CREATE TRIGGER subcampania_historial_prevent_mutation_trg
  BEFORE UPDATE OR DELETE OR TRUNCATE ON public.subcampania_historial
  FOR EACH STATEMENT EXECUTE FUNCTION public.fn_subcampania_historial_prevent_mutation();
CREATE TABLE public.registro_plantacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subcampania_id BIGINT NOT NULL REFERENCES public.subcampania(id),
  responsable_id BIGINT NOT NULL REFERENCES public.usuario(id),
  fecha_plantacion DATE NOT NULL,
  cantidad_total_plantada INT NOT NULL CHECK(cantidad_total_plantada>0),
  nombre_responsable_snapshot TEXT, observaciones TEXT,
  codigo_trazabilidad TEXT NOT NULL UNIQUE,
  created_by BIGINT NOT NULL REFERENCES public.usuario(id)
);
-- Relaciones mínimas de las otras fuentes del export de manifest, sin hechos.
CREATE TABLE public.registro_plantacion_coresponsable (
  id BIGINT PRIMARY KEY, registro_plantacion_id BIGINT REFERENCES public.registro_plantacion(id),
  usuario_id BIGINT REFERENCES public.usuario(id)
);
CREATE TABLE public.evento_plantacion (
  id BIGINT PRIMARY KEY, subcampania_id BIGINT REFERENCES public.subcampania(id),
  responsable_id BIGINT REFERENCES public.usuario(id)
);
CREATE TABLE public.asignacion_vivero_subcampania (
  id BIGINT PRIMARY KEY, subcampania_id BIGINT REFERENCES public.subcampania(id),
  usuario_asignacion_id BIGINT REFERENCES public.usuario(id)
);

